import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import XLSX from 'xlsx'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const xlsPath = join(root, 'Deudas Proveedores', 'Listado De Deudas A Proveedores.XLS')

const wb = XLSX.readFile(xlsPath)
const data = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { header: 1, defval: '' })

const rows = []
for (let i = 8; i < data.length; i++) {
  const r = data[i]
  const codigo = String(r[0] || '').trim()
  if (codigo === 'TOTAL') break
  if (!/^\d{4,6}$/.test(codigo)) continue
  const saldo = typeof r[10] === 'number' ? r[10] : 0
  rows.push({
    codigo,
    razon_social: String(r[2] || '').trim(),
    telefono: String(r[7] || '').trim() || '-',
    saldo
  })
}

const seed = { fecha_corte: '2026-06-19', rows }
writeFileSync(join(root, 'scripts/deudas-proveedores-seed.json'), JSON.stringify(seed, null, 2))

const esc = (s) => String(s).replace(/'/g, "''")

const inserts = seed.rows
  .map(
    (r) =>
      `  ('${esc(r.codigo)}', '${esc(r.razon_social)}', '${esc(r.telefono)}', ${r.saldo.toFixed(2)}, '${seed.fecha_corte}')`
  )
  .join(',\n')

const sql = `-- Deudas a proveedores (migrado desde Listado De Deudas A Proveedores.XLS)
BEGIN;

CREATE TABLE IF NOT EXISTS public.deudas_proveedores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(20) NOT NULL UNIQUE,
  razon_social text NOT NULL,
  telefono varchar(80) DEFAULT '-',
  saldo numeric(15,2) NOT NULL DEFAULT 0,
  id_proveedor integer REFERENCES public.proveedores(id) ON DELETE SET NULL,
  fecha_corte date NOT NULL DEFAULT CURRENT_DATE,
  notas text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_deudas_proveedores_proveedor ON public.deudas_proveedores(id_proveedor);
CREATE INDEX IF NOT EXISTS idx_deudas_proveedores_codigo ON public.deudas_proveedores(codigo);

ALTER TABLE public.deudas_proveedores ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS deudas_proveedores_all ON public.deudas_proveedores;
CREATE POLICY deudas_proveedores_all ON public.deudas_proveedores FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

INSERT INTO public.deudas_proveedores (codigo, razon_social, telefono, saldo, fecha_corte)
VALUES
${inserts}
ON CONFLICT (codigo) DO UPDATE SET
  razon_social = EXCLUDED.razon_social,
  telefono = EXCLUDED.telefono,
  saldo = EXCLUDED.saldo,
  fecha_corte = EXCLUDED.fecha_corte,
  updated_at = now();

CREATE OR REPLACE FUNCTION public.vincular_deudas_proveedores()
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE v_count integer;
BEGIN
  UPDATE public.deudas_proveedores d
  SET id_proveedor = p.id, updated_at = now()
  FROM public.proveedores p
  WHERE d.id_proveedor IS NULL
    AND (
      upper(trim(coalesce(p.razon_social, ''))) = upper(trim(d.razon_social))
      OR upper(trim(p.nombre)) = upper(trim(d.razon_social))
      OR upper(trim(p.nombre)) LIKE '%' || upper(trim(split_part(d.razon_social, ',', 1))) || '%'
    );
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

SELECT public.vincular_deudas_proveedores();

COMMIT;
`

writeFileSync(join(root, 'supabase/patches/2026-06-19_deudas_proveedores.sql'), sql)
console.log('Rows:', rows.length, 'Total:', rows.reduce((s, x) => s + x.saldo, 0).toFixed(2))
