import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import XLSX from 'xlsx'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const xlsPath = join(
  root,
  'Deudas Proveedores',
  'Pago',
  'Planilla de Pagos a Proveedores_19-06-2026 08-55-49.XLS'
)

function parseFechaAR(s) {
  const m = String(s || '').match(/(\d{2})\/(\d{2})\/(\d{4})/)
  if (!m) return null
  return `${m[3]}-${m[2]}-${m[1]}`
}

const wb = XLSX.readFile(xlsPath)
const data = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { header: 1, defval: '' })

let fechaDesde = '2026-01-01'
let fechaHasta = '2026-06-19'
let proveedorFiltro = ''

const row3 = String(data[3]?.[1] || '')
const desdeHasta = row3.match(/Desde (\d{2}\/\d{2}\/\d{4}) hasta (\d{2}\/\d{2}\/\d{4})/i)
if (desdeHasta) {
  fechaDesde = parseFechaAR(desdeHasta[1]) || fechaDesde
  fechaHasta = parseFechaAR(desdeHasta[2]) || fechaHasta
}
if (data[4]?.[1]) proveedorFiltro = String(data[4][1]).trim()

const rows = []
for (let i = 7; i < data.length; i++) {
  const r = data[i]
  const fechaRaw = String(r[0] || '').trim()
  if (!fechaRaw || fechaRaw.toLowerCase().startsWith('total')) break
  if (!/^\d{2}\/\d{2}\/\d{4}$/.test(fechaRaw)) continue

  const monto =
    typeof r[10] === 'number'
      ? r[10]
      : parseFloat(String(r[10] || '0').replace(/\./g, '').replace(',', '.')) || 0

  rows.push({
    fecha: parseFechaAR(fechaRaw),
    numero_pago: String(r[1] || '').trim(),
    numero_recibo: String(r[2] || '').trim(),
    proveedor_nombre: String(r[4] || r[3] || '').trim(),
    usuario: String(r[8] || r[5] || '').trim(),
    monto
  })
}

const seed = { fecha_desde: fechaDesde, fecha_hasta: fechaHasta, proveedor_filtro: proveedorFiltro, rows }
writeFileSync(join(root, 'scripts/pagos-proveedores-seed.json'), JSON.stringify(seed, null, 2))

const esc = (s) => String(s).replace(/'/g, "''")

const inserts = seed.rows
  .map(
    (r) =>
      `  ('${r.fecha}', '${esc(r.numero_pago)}', '${esc(r.numero_recibo)}', '${esc(r.proveedor_nombre)}', '${esc(r.usuario)}', ${r.monto.toFixed(2)}, '${seed.fecha_desde}', '${seed.fecha_hasta}')`
  )
  .join(',\n')

const sql = `-- Pagos a proveedores (migrado desde Planilla de Pagos a Proveedores.XLS)
BEGIN;

CREATE TABLE IF NOT EXISTS public.pagos_proveedores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha date NOT NULL,
  numero_pago varchar(50) NOT NULL,
  numero_recibo varchar(50) NOT NULL DEFAULT '',
  proveedor_nombre text NOT NULL,
  usuario varchar(80),
  monto numeric(15,2) NOT NULL DEFAULT 0,
  id_proveedor integer REFERENCES public.proveedores(id) ON DELETE SET NULL,
  id_pago_cobro integer REFERENCES public.pagos_cobros(id) ON DELETE SET NULL,
  fecha_desde date,
  fecha_hasta date,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(numero_pago, numero_recibo)
);

CREATE INDEX IF NOT EXISTS idx_pagos_proveedores_fecha ON public.pagos_proveedores(fecha DESC);
CREATE INDEX IF NOT EXISTS idx_pagos_proveedores_proveedor ON public.pagos_proveedores(id_proveedor);
CREATE INDEX IF NOT EXISTS idx_pagos_proveedores_nombre ON public.pagos_proveedores(proveedor_nombre);

ALTER TABLE public.pagos_proveedores ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS pagos_proveedores_all ON public.pagos_proveedores;
CREATE POLICY pagos_proveedores_all ON public.pagos_proveedores FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

INSERT INTO public.pagos_proveedores (fecha, numero_pago, numero_recibo, proveedor_nombre, usuario, monto, fecha_desde, fecha_hasta)
VALUES
${inserts}
ON CONFLICT (numero_pago, numero_recibo) DO UPDATE SET
  fecha = EXCLUDED.fecha,
  proveedor_nombre = EXCLUDED.proveedor_nombre,
  usuario = EXCLUDED.usuario,
  monto = EXCLUDED.monto,
  fecha_desde = EXCLUDED.fecha_desde,
  fecha_hasta = EXCLUDED.fecha_hasta,
  updated_at = now();

CREATE OR REPLACE FUNCTION public.vincular_pagos_proveedores()
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE v_count integer;
BEGIN
  UPDATE public.pagos_proveedores p
  SET id_proveedor = pr.id, updated_at = now()
  FROM public.proveedores pr
  WHERE p.id_proveedor IS NULL
    AND (
      upper(trim(coalesce(pr.razon_social, ''))) = upper(trim(p.proveedor_nombre))
      OR upper(trim(pr.nombre)) = upper(trim(p.proveedor_nombre))
      OR upper(trim(pr.nombre)) LIKE '%' || upper(trim(split_part(p.proveedor_nombre, ' ', 1))) || '%'
    );
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

SELECT public.vincular_pagos_proveedores();

COMMIT;
`

writeFileSync(join(root, 'supabase/patches/2026-06-19_pagos_proveedores.sql'), sql)
console.log('Rows:', rows.length, 'Total:', rows.reduce((s, x) => s + x.monto, 0).toFixed(2))
