import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import XLSX from 'xlsx'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const xlsPath = join(
  root,
  'Deudas Proveedores',
  'Movimientos',
  'Listado de Movimientos de Proveedores IGENAR ARGENTINA S.A. (1).XLS'
)

function parseFechaAR(s) {
  const raw = String(s || '').split(' ')[0]
  const m = raw.match(/(\d{2})\/(\d{2})\/(\d{4})/)
  if (!m) return null
  return `${m[3]}-${m[2]}-${m[1]}`
}

function parseFechaHoraAR(s) {
  const str = String(s || '').trim()
  const m = str.match(/(\d{2})\/(\d{2})\/(\d{4})\s+(\d{2}):(\d{2}):(\d{2})/)
  if (!m) return parseFechaAR(str)
  return `${m[3]}-${m[2]}-${m[1]}T${m[4]}:${m[5]}:${m[6]}`
}

const wb = XLSX.readFile(xlsPath)
const data = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { header: 1, defval: '' })

const proveedorNombre = String(data[2]?.[2] || data[2]?.[1] || '').trim() || 'IGENAR ARGENTINA S.A.'
const moneda = String(data[2]?.[8] || 'PESOS').trim()

const periodo = String(data[3]?.[1] || '')
const periodoMatch = periodo.match(/Desde (\d{2}\/\d{2}\/\d{4})\s+Hasta (\d{2}\/\d{2}\/\d{4})/i)
const fechaDesde = periodoMatch ? parseFechaAR(periodoMatch[1]) : '2025-12-31'
const fechaHasta = periodoMatch ? parseFechaAR(periodoMatch[2]) : '2026-06-19'

const rows = []
for (let i = 5; i < data.length; i++) {
  const r = data[i]
  const col0 = String(r[0] || '').trim()
  if (!col0 || col0.toLowerCase() === 'totales') break

  const tipo = String(r[3] || '').trim()
  const comprobante = String(r[6] || '').trim()
  const esSaldoInicial = comprobante.toLowerCase().includes('saldo al inicio') || tipo === '-'

  const num = (v) => (typeof v === 'number' ? v : parseFloat(String(v || '0').replace(/\./g, '').replace(',', '.')) || 0)

  rows.push({
    proveedor_nombre: proveedorNombre,
    moneda,
    fecha_desde: fechaDesde,
    fecha_hasta: fechaHasta,
    fecha_hora: parseFechaHoraAR(r[0]),
    fecha_comprobante: parseFechaAR(r[2]) || parseFechaAR(r[0]),
    tipo_movimiento: esSaldoInicial ? 'SALDO INICIAL' : tipo,
    comprobante: comprobante || '—',
    debe: num(r[8]),
    haber: num(r[9]),
    saldo: num(r[10]),
    es_saldo_inicial: esSaldoInicial
  })
}

const seed = { proveedor_nombre: proveedorNombre, moneda, fecha_desde: fechaDesde, fecha_hasta: fechaHasta, rows }
writeFileSync(join(root, 'scripts/movimientos-proveedores-seed.json'), JSON.stringify(seed, null, 2))

const esc = (s) => String(s).replace(/'/g, "''")

const inserts = seed.rows
  .map(
    (r) =>
      `  ('${esc(r.proveedor_nombre)}', '${esc(r.moneda)}', '${r.fecha_desde}', '${r.fecha_hasta}', '${r.fecha_hora}', '${r.fecha_comprobante}', '${esc(r.tipo_movimiento)}', '${esc(r.comprobante)}', ${r.debe.toFixed(2)}, ${r.haber.toFixed(2)}, ${r.saldo.toFixed(2)}, ${r.es_saldo_inicial})`
  )
  .join(',\n')

const sql = `-- Movimientos de proveedores (migrado desde Listado de Movimientos.XLS)
BEGIN;

CREATE TABLE IF NOT EXISTS public.movimientos_proveedores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_nombre text NOT NULL,
  moneda varchar(20) NOT NULL DEFAULT 'PESOS',
  fecha_desde date,
  fecha_hasta date,
  fecha_hora timestamptz NOT NULL,
  fecha_comprobante date,
  tipo_movimiento text NOT NULL,
  comprobante varchar(120) NOT NULL DEFAULT '',
  debe numeric(15,2) NOT NULL DEFAULT 0,
  haber numeric(15,2) NOT NULL DEFAULT 0,
  saldo numeric(15,2) NOT NULL DEFAULT 0,
  es_saldo_inicial boolean NOT NULL DEFAULT false,
  id_proveedor integer REFERENCES public.proveedores(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(proveedor_nombre, fecha_hora, comprobante, tipo_movimiento)
);

CREATE INDEX IF NOT EXISTS idx_mov_prov_proveedor ON public.movimientos_proveedores(id_proveedor);
CREATE INDEX IF NOT EXISTS idx_mov_prov_fecha ON public.movimientos_proveedores(fecha_hora DESC);
CREATE INDEX IF NOT EXISTS idx_mov_prov_comprobante ON public.movimientos_proveedores(comprobante);

ALTER TABLE public.movimientos_proveedores ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS movimientos_proveedores_all ON public.movimientos_proveedores;
CREATE POLICY movimientos_proveedores_all ON public.movimientos_proveedores FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

INSERT INTO public.movimientos_proveedores (
  proveedor_nombre, moneda, fecha_desde, fecha_hasta, fecha_hora, fecha_comprobante,
  tipo_movimiento, comprobante, debe, haber, saldo, es_saldo_inicial
)
VALUES
${inserts}
ON CONFLICT (proveedor_nombre, fecha_hora, comprobante, tipo_movimiento) DO UPDATE SET
  debe = EXCLUDED.debe,
  haber = EXCLUDED.haber,
  saldo = EXCLUDED.saldo,
  fecha_comprobante = EXCLUDED.fecha_comprobante,
  updated_at = now();

CREATE OR REPLACE FUNCTION public.vincular_movimientos_proveedores()
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE v_count integer;
BEGIN
  UPDATE public.movimientos_proveedores m
  SET id_proveedor = p.id, updated_at = now()
  FROM public.proveedores p
  WHERE m.id_proveedor IS NULL
    AND (
      upper(trim(coalesce(p.razon_social, ''))) = upper(trim(m.proveedor_nombre))
      OR upper(trim(p.nombre)) = upper(trim(m.proveedor_nombre))
      OR upper(trim(p.nombre)) LIKE '%' || upper(trim(split_part(m.proveedor_nombre, ' ', 1))) || '%'
    );
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

SELECT public.vincular_movimientos_proveedores();

COMMIT;
`

writeFileSync(join(root, 'supabase/patches/2026-06-19_movimientos_proveedores.sql'), sql)
console.log('Rows:', rows.length, 'Proveedor:', proveedorNombre)
