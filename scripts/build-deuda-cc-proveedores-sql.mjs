import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import XLSX from 'xlsx'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const xlsPath = join(
  root,
  'Deudas Proveedores',
  'Deuda Total een Cuenta Corriente',
  'Deuda Total en Cuenta Corriente IGENAR ARGENTINA S.A..XLS'
)

function parseFechaAR(s) {
  const raw = String(s || '').split(' ')[0]
  const m = raw.match(/(\d{2})\/(\d{2})\/(\d{4})/)
  if (!m) return null
  return `${m[3]}-${m[2]}-${m[1]}`
}

function num(v) {
  if (typeof v === 'number' && Number.isFinite(v)) return v
  const s = String(v || '')
    .replace(/\$/g, '')
    .replace(/\(/g, '-')
    .replace(/\)/g, '')
    .trim()
  if (!s) return 0
  return parseFloat(s.replace(/\./g, '').replace(',', '.')) || 0
}

function parseDiasVencido(s) {
  const m = String(s || '').match(/(\d+)\s*venc/i)
  return m ? Number(m[1]) : null
}

const wb = XLSX.readFile(xlsPath)
const data = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { header: 1, defval: '' })

const provRaw = String(data[2]?.[2] || '').trim()
const provMatch = provRaw.match(/^(\d+)\s*-\s*(.+)$/i)
const proveedor_codigo = provMatch ? provMatch[1].padStart(5, '0') : ''
const proveedor_nombre = provMatch ? provMatch[2].trim() : provRaw || 'IGENAR ARGENTINA S.A.'

let fecha_corte = '2026-06-19'
for (let i = data.length - 1; i >= 0; i--) {
  const f = parseFechaAR(data[i]?.[0])
  if (f) {
    fecha_corte = f
    break
  }
}

const rows = []
for (let i = 7; i < data.length; i++) {
  const r = data[i]
  const tipo = String(r[0] || '').trim()
  if (!tipo || tipo.toLowerCase().includes('total')) break
  if (!/^(FA|NDA|NCA|ND|NC|PA|OP)/i.test(tipo)) continue

  const numero = String(r[1] || '').trim()
  rows.push({
    proveedor_codigo,
    proveedor_nombre,
    fecha_corte,
    tipo_comprobante: tipo,
    numero_comprobante: numero,
    fecha_comprobante: parseFechaAR(r[2]),
    fecha_vencimiento: parseFechaAR(r[3]),
    total: num(r[4] !== '' && r[4] != null ? r[4] : r[9]),
    pagado: num(r[6]),
    deuda: num(r[7] !== '' && r[7] != null ? r[7] : r[4]),
    dias_vencido: parseDiasVencido(r[8]),
    total_moneda_origen: String(r[9] || '').trim() || null,
    total_actualizado: num(r[10] !== '' && r[10] != null ? r[10] : r[7])
  })
}

const findTotal = (label) => {
  const row = data.find((r) => String(r[0] || '').toLowerCase().includes(label))
  if (!row) return 0
  return num(row[2] !== '' && row[2] != null ? row[2] : row[3])
}

const resumen = {
  total_comprobantes: findTotal('total comprobantes'),
  total_cheques: findTotal('total cheques'),
  total_cta_cte: findTotal('total cta')
}

const seed = {
  proveedor_codigo,
  proveedor_nombre,
  fecha_corte,
  resumen,
  rows
}

writeFileSync(join(root, 'scripts/deuda-cc-proveedores-seed.json'), JSON.stringify(seed, null, 2))
writeFileSync(join(root, 'src/data/deuda-cc-proveedores-seed.json'), JSON.stringify(seed, null, 2))

const esc = (s) => String(s ?? '').replace(/'/g, "''")

const inserts = rows
  .map(
    (r) =>
      `  ('${esc(r.proveedor_codigo)}', '${esc(r.proveedor_nombre)}', '${r.fecha_corte}', '${esc(r.tipo_comprobante)}', '${esc(r.numero_comprobante)}', ${r.fecha_comprobante ? `'${r.fecha_comprobante}'` : 'NULL'}, ${r.fecha_vencimiento ? `'${r.fecha_vencimiento}'` : 'NULL'}, ${r.total.toFixed(2)}, ${r.pagado.toFixed(2)}, ${r.deuda.toFixed(2)}, ${r.dias_vencido ?? 'NULL'}, ${r.total_moneda_origen ? `'${esc(r.total_moneda_origen)}'` : 'NULL'}, ${r.total_actualizado.toFixed(2)})`
  )
  .join(',\n')

const sql = `-- Deuda total en cuenta corriente proveedores (migrado desde Deuda Total en Cuenta Corriente.XLS)
BEGIN;

CREATE TABLE IF NOT EXISTS public.deuda_cc_proveedores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_codigo varchar(20) NOT NULL DEFAULT '',
  proveedor_nombre text NOT NULL,
  fecha_corte date NOT NULL,
  tipo_comprobante varchar(10) NOT NULL,
  numero_comprobante varchar(50) NOT NULL,
  fecha_comprobante date,
  fecha_vencimiento date,
  total numeric(15,2) NOT NULL DEFAULT 0,
  pagado numeric(15,2) NOT NULL DEFAULT 0,
  deuda numeric(15,2) NOT NULL DEFAULT 0,
  dias_vencido integer,
  total_moneda_origen text,
  total_actualizado numeric(15,2) NOT NULL DEFAULT 0,
  id_proveedor integer REFERENCES public.proveedores(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(proveedor_nombre, tipo_comprobante, numero_comprobante, fecha_comprobante)
);

CREATE INDEX IF NOT EXISTS idx_deuda_cc_prov_proveedor ON public.deuda_cc_proveedores(id_proveedor);
CREATE INDEX IF NOT EXISTS idx_deuda_cc_prov_fecha ON public.deuda_cc_proveedores(fecha_vencimiento);
CREATE INDEX IF NOT EXISTS idx_deuda_cc_prov_deuda ON public.deuda_cc_proveedores(deuda DESC);

ALTER TABLE public.deuda_cc_proveedores ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS deuda_cc_proveedores_all ON public.deuda_cc_proveedores;
CREATE POLICY deuda_cc_proveedores_all ON public.deuda_cc_proveedores FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

INSERT INTO public.deuda_cc_proveedores (
  proveedor_codigo, proveedor_nombre, fecha_corte, tipo_comprobante, numero_comprobante,
  fecha_comprobante, fecha_vencimiento, total, pagado, deuda, dias_vencido,
  total_moneda_origen, total_actualizado
)
VALUES
${inserts}
ON CONFLICT (proveedor_nombre, tipo_comprobante, numero_comprobante, fecha_comprobante) DO UPDATE SET
  total = EXCLUDED.total,
  pagado = EXCLUDED.pagado,
  deuda = EXCLUDED.deuda,
  dias_vencido = EXCLUDED.dias_vencido,
  total_actualizado = EXCLUDED.total_actualizado,
  fecha_vencimiento = EXCLUDED.fecha_vencimiento,
  fecha_corte = EXCLUDED.fecha_corte,
  updated_at = now();

CREATE OR REPLACE FUNCTION public.vincular_deuda_cc_proveedores()
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE v_count integer;
BEGIN
  UPDATE public.deuda_cc_proveedores d
  SET id_proveedor = p.id, updated_at = now()
  FROM public.proveedores p
  WHERE d.id_proveedor IS NULL
    AND (
      upper(trim(coalesce(p.razon_social, ''))) = upper(trim(d.proveedor_nombre))
      OR upper(trim(p.nombre)) = upper(trim(d.proveedor_nombre))
      OR upper(trim(p.nombre)) LIKE '%' || upper(trim(split_part(d.proveedor_nombre, ' ', 1))) || '%'
    );
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

SELECT public.vincular_deuda_cc_proveedores();

COMMIT;
`

writeFileSync(join(root, 'supabase/patches/2026-06-19_deuda_cc_proveedores.sql'), sql)
console.log('Rows:', rows.length, 'Proveedor:', proveedor_nombre, 'Resumen:', resumen)
