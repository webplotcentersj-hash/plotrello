-- Actualizar capacitación
CREATE OR REPLACE FUNCTION public.actualizar_capacitacion(
  p_id integer,
  p_titulo varchar DEFAULT NULL,
  p_descripcion text DEFAULT NULL,
  p_tipo_capacitacion varchar DEFAULT NULL,
  p_categoria varchar DEFAULT NULL,
  p_duracion_horas numeric DEFAULT NULL,
  p_fecha_inicio date DEFAULT NULL,
  p_fecha_fin date DEFAULT NULL,
  p_fecha_limite_inscripcion date DEFAULT NULL,
  p_cupo_maximo integer DEFAULT NULL,
  p_lugar varchar DEFAULT NULL,
  p_link_virtual text DEFAULT NULL,
  p_instructor varchar DEFAULT NULL,
  p_estado varchar DEFAULT NULL,
  p_es_obligatoria boolean DEFAULT NULL,
  p_requiere_aprobacion boolean DEFAULT NULL,
  p_material_adjunto_url text DEFAULT NULL,
  p_observaciones text DEFAULT NULL
)
RETURNS public.capacitaciones
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_result public.capacitaciones;
BEGIN
  UPDATE public.capacitaciones
  SET
    titulo = COALESCE(p_titulo, titulo),
    descripcion = COALESCE(p_descripcion, descripcion),
    tipo_capacitacion = COALESCE(p_tipo_capacitacion, tipo_capacitacion),
    categoria = COALESCE(p_categoria, categoria),
    duracion_horas = COALESCE(p_duracion_horas, duracion_horas),
    fecha_inicio = COALESCE(p_fecha_inicio, fecha_inicio),
    fecha_fin = COALESCE(p_fecha_fin, fecha_fin),
    fecha_limite_inscripcion = COALESCE(p_fecha_limite_inscripcion, fecha_limite_inscripcion),
    cupo_maximo = COALESCE(p_cupo_maximo, cupo_maximo),
    lugar = COALESCE(p_lugar, lugar),
    link_virtual = COALESCE(p_link_virtual, link_virtual),
    instructor = COALESCE(p_instructor, instructor),
    estado = COALESCE(p_estado, estado),
    es_obligatoria = COALESCE(p_es_obligatoria, es_obligatoria),
    requiere_aprobacion = COALESCE(p_requiere_aprobacion, requiere_aprobacion),
    material_adjunto_url = COALESCE(p_material_adjunto_url, material_adjunto_url),
    observaciones = COALESCE(p_observaciones, observaciones),
    updated_at = now()
  WHERE id = p_id;

  SELECT * INTO v_result FROM public.capacitaciones WHERE id = p_id;
  RETURN v_result;
END;
$$;

-- Registrar asistencia y calificación
CREATE OR REPLACE FUNCTION public.registrar_asistencia_capacitacion(
  p_id_inscripcion integer,
  p_asistio boolean,
  p_calificacion numeric DEFAULT NULL,
  p_comentarios text DEFAULT NULL
)
RETURNS public.capacitaciones_inscripciones
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_result public.capacitaciones_inscripciones;
BEGIN
  UPDATE public.capacitaciones_inscripciones
  SET
    asistio = p_asistio,
    calificacion = COALESCE(p_calificacion, calificacion),
    comentarios = COALESCE(p_comentarios, comentarios),
    estado = CASE WHEN p_asistio THEN 'completado' ELSE 'ausente' END,
    updated_at = now()
  WHERE id = p_id_inscripcion;

  SELECT * INTO v_result FROM public.capacitaciones_inscripciones WHERE id = p_id_inscripcion;
  RETURN v_result;
END;
$$;

-- Cancelar inscripción
CREATE OR REPLACE FUNCTION public.cancelar_inscripcion(
  p_id_inscripcion integer,
  p_id_usuario integer
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  UPDATE public.capacitaciones_inscripciones
  SET estado = 'cancelado', updated_at = now()
  WHERE id = p_id_inscripcion 
    AND id_usuario = p_id_usuario
    AND estado IN ('pendiente', 'inscrito', 'aprobado');

  RETURN FOUND;
END;
$$;

-- Eliminar capacitación
CREATE OR REPLACE FUNCTION public.eliminar_capacitacion(p_id integer)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  DELETE FROM public.capacitaciones WHERE id = p_id;
  RETURN FOUND;
END;
$$;

