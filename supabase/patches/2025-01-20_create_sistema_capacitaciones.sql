-- ============================================
-- 1. TABLA DE CAPACITACIONES
-- ============================================
CREATE TABLE IF NOT EXISTS public.capacitaciones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo varchar(255) NOT NULL,
  descripcion text,
  tipo_capacitacion varchar(100) NOT NULL DEFAULT 'presencial', -- 'presencial', 'virtual', 'mixta', 'online'
  categoria varchar(100), -- 'tecnica', 'seguridad', 'soft_skills', 'compliance', 'otra'
  duracion_horas numeric(5,2), -- Duración en horas
  fecha_inicio date,
  fecha_fin date,
  fecha_limite_inscripcion date,
  cupo_maximo integer,
  lugar varchar(255), -- Para capacitaciones presenciales
  link_virtual text, -- Para capacitaciones virtuales
  instructor varchar(255),
  estado varchar(50) DEFAULT 'planificada', -- 'planificada', 'abierta', 'en_curso', 'completada', 'cancelada'
  es_obligatoria boolean DEFAULT false,
  requiere_aprobacion boolean DEFAULT true,
  material_adjunto_url text, -- URL de materiales, PDFs, etc.
  observaciones text,
  creado_por integer NOT NULL REFERENCES public.usuarios(id),
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_capacitaciones_estado ON public.capacitaciones(estado);
CREATE INDEX IF NOT EXISTS idx_capacitaciones_tipo ON public.capacitaciones(tipo_capacitacion);
CREATE INDEX IF NOT EXISTS idx_capacitaciones_categoria ON public.capacitaciones(categoria);
CREATE INDEX IF NOT EXISTS idx_capacitaciones_fecha_inicio ON public.capacitaciones(fecha_inicio);
CREATE INDEX IF NOT EXISTS idx_capacitaciones_creado_por ON public.capacitaciones(creado_por);

-- ============================================
-- 2. TABLA DE INSCRIPCIONES
-- ============================================
CREATE TABLE IF NOT EXISTS public.capacitaciones_inscripciones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_capacitacion integer NOT NULL REFERENCES public.capacitaciones(id) ON DELETE CASCADE,
  id_usuario integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  fecha_inscripcion timestamptz DEFAULT now(),
  estado varchar(50) DEFAULT 'pendiente', -- 'pendiente', 'inscrito', 'aprobado', 'rechazado', 'completado', 'ausente', 'cancelado'
  asistio boolean DEFAULT false,
  calificacion numeric(4,2), -- Calificación obtenida (0-10)
  comentarios text,
  aprobado_por integer REFERENCES public.usuarios(id),
  fecha_aprobacion timestamptz,
  motivo_rechazo text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  UNIQUE(id_capacitacion, id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_inscripciones_capacitacion ON public.capacitaciones_inscripciones(id_capacitacion);
CREATE INDEX IF NOT EXISTS idx_inscripciones_usuario ON public.capacitaciones_inscripciones(id_usuario);
CREATE INDEX IF NOT EXISTS idx_inscripciones_estado ON public.capacitaciones_inscripciones(estado);

