-- Crear capacitación
CREATE OR REPLACE FUNCTION public.crear_capacitacion(
  p_titulo varchar,
  p_descripcion text,
  p_tipo_capacitacion varchar DEFAULT 'presencial',
  p_categoria varchar DEFAULT NULL,
  p_duracion_horas numeric DEFAULT NULL,
  p_fecha_inicio date DEFAULT NULL,
  p_fecha_fin date DEFAULT NULL,
  p_fecha_limite_inscripcion date DEFAULT NULL,
  p_cupo_maximo integer DEFAULT NULL,
  p_lugar varchar DEFAULT NULL,
  p_link_virtual text DEFAULT NULL,
  p_instructor varchar DEFAULT NULL,
  p_es_obligatoria boolean DEFAULT false,
  p_requiere_aprobacion boolean DEFAULT true,
  p_material_adjunto_url text DEFAULT NULL,
  p_observaciones text DEFAULT NULL,
  p_creado_por integer
)
RETURNS public.capacitaciones
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_result public.capacitaciones;
BEGIN
  INSERT INTO public.capacitaciones (
    titulo, descripcion, tipo_capacitacion, categoria, duracion_horas,
    fecha_inicio, fecha_fin, fecha_limite_inscripcion, cupo_maximo,
    lugar, link_virtual, instructor, es_obligatoria, requiere_aprobacion,
    material_adjunto_url, observaciones, creado_por
  )
  VALUES (
    p_titulo, p_descripcion, p_tipo_capacitacion, p_categoria, p_duracion_horas,
    p_fecha_inicio, p_fecha_fin, p_fecha_limite_inscripcion, p_cupo_maximo,
    p_lugar, p_link_virtual, p_instructor, p_es_obligatoria, p_requiere_aprobacion,
    p_material_adjunto_url, p_observaciones, p_creado_por
  )
  RETURNING * INTO v_result;

  RETURN v_result;
END;
$$;

-- Listar capacitaciones
CREATE OR REPLACE FUNCTION public.obtener_capacitaciones(
  p_estado varchar DEFAULT NULL,
  p_tipo_capacitacion varchar DEFAULT NULL,
  p_categoria varchar DEFAULT NULL,
  p_fecha_desde date DEFAULT NULL,
  p_fecha_hasta date DEFAULT NULL,
  p_id_usuario integer DEFAULT NULL -- Si se proporciona, incluye estado de inscripción
)
RETURNS TABLE (
  id integer,
  titulo varchar,
  descripcion text,
  tipo_capacitacion varchar,
  categoria varchar,
  duracion_horas numeric,
  fecha_inicio date,
  fecha_fin date,
  fecha_limite_inscripcion date,
  cupo_maximo integer,
  lugar varchar,
  link_virtual text,
  instructor varchar,
  estado varchar,
  es_obligatoria boolean,
  requiere_aprobacion boolean,
  material_adjunto_url text,
  observaciones text,
  creado_por integer,
  creado_por_nombre varchar,
  inscripciones_count integer,
  cupos_disponibles integer,
  usuario_inscrito boolean,
  estado_inscripcion varchar,
  created_at timestamptz,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    c.id,
    c.titulo,
    c.descripcion,
    c.tipo_capacitacion,
    c.categoria,
    c.duracion_horas,
    c.fecha_inicio,
    c.fecha_fin,
    c.fecha_limite_inscripcion,
    c.cupo_maximo,
    c.lugar,
    c.link_virtual,
    c.instructor,
    c.estado,
    c.es_obligatoria,
    c.requiere_aprobacion,
    c.material_adjunto_url,
    c.observaciones,
    c.creado_por,
    u.nombre::varchar AS creado_por_nombre,
    COUNT(DISTINCT ci.id)::integer AS inscripciones_count,
    CASE 
      WHEN c.cupo_maximo IS NOT NULL THEN 
        GREATEST(0, c.cupo_maximo - COUNT(DISTINCT CASE WHEN ci.estado IN ('inscrito', 'aprobado', 'completado') THEN ci.id END))
      ELSE NULL
    END::integer AS cupos_disponibles,
    CASE WHEN p_id_usuario IS NOT NULL AND EXISTS (
      SELECT 1 FROM public.capacitaciones_inscripciones 
      WHERE id_capacitacion = c.id AND id_usuario = p_id_usuario
    ) THEN true ELSE false END AS usuario_inscrito,
    COALESCE(
      (SELECT ci2.estado FROM public.capacitaciones_inscripciones ci2 
       WHERE ci2.id_capacitacion = c.id AND ci2.id_usuario = p_id_usuario LIMIT 1),
      NULL
    )::varchar AS estado_inscripcion,
    c.created_at,
    c.updated_at
  FROM public.capacitaciones c
  LEFT JOIN public.usuarios u ON u.id = c.creado_por
  LEFT JOIN public.capacitaciones_inscripciones ci ON ci.id_capacitacion = c.id
  WHERE
    (p_estado IS NULL OR c.estado = p_estado)
    AND (p_tipo_capacitacion IS NULL OR c.tipo_capacitacion = p_tipo_capacitacion)
    AND (p_categoria IS NULL OR c.categoria = p_categoria)
    AND (p_fecha_desde IS NULL OR c.fecha_inicio >= p_fecha_desde)
    AND (p_fecha_hasta IS NULL OR c.fecha_inicio <= p_fecha_hasta)
  GROUP BY c.id, u.nombre
  ORDER BY c.fecha_inicio DESC, c.created_at DESC;
END;
$$;

-- Inscribirse a capacitación
CREATE OR REPLACE FUNCTION public.inscribirse_capacitacion(
  p_id_capacitacion integer,
  p_id_usuario integer
)
RETURNS public.capacitaciones_inscripciones
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_capacitacion public.capacitaciones;
  v_cupos_disponibles integer;
  v_inscripcion_existente integer;
  v_result public.capacitaciones_inscripciones;
BEGIN
  -- Verificar que la capacitación existe
  SELECT * INTO v_capacitacion FROM public.capacitaciones WHERE id = p_id_capacitacion;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Capacitación no encontrada';
  END IF;

  -- Verificar que no esté ya inscrito
  SELECT id INTO v_inscripcion_existente 
  FROM public.capacitaciones_inscripciones 
  WHERE id_capacitacion = p_id_capacitacion AND id_usuario = p_id_usuario;
  
  IF v_inscripcion_existente IS NOT NULL THEN
    RAISE EXCEPTION 'Ya estás inscrito en esta capacitación';
  END IF;

  -- Verificar cupos disponibles
  IF v_capacitacion.cupo_maximo IS NOT NULL THEN
    SELECT COUNT(*) INTO v_cupos_disponibles
    FROM public.capacitaciones_inscripciones
    WHERE id_capacitacion = p_id_capacitacion 
      AND estado IN ('inscrito', 'aprobado', 'completado');
    
    IF v_cupos_disponibles >= v_capacitacion.cupo_maximo THEN
      RAISE EXCEPTION 'No hay cupos disponibles';
    END IF;
  END IF;

  -- Verificar fecha límite
  IF v_capacitacion.fecha_limite_inscripcion IS NOT NULL 
     AND v_capacitacion.fecha_limite_inscripcion < CURRENT_DATE THEN
    RAISE EXCEPTION 'La fecha límite de inscripción ha pasado';
  END IF;

  -- Crear inscripción
  INSERT INTO public.capacitaciones_inscripciones (
    id_capacitacion, id_usuario, estado
  )
  VALUES (
    p_id_capacitacion, p_id_usuario,
    CASE WHEN v_capacitacion.requiere_aprobacion THEN 'pendiente' ELSE 'inscrito' END
  )
  RETURNING * INTO v_result;

  RETURN v_result;
END;
$$;

-- Aprobar/Rechazar inscripción
CREATE OR REPLACE FUNCTION public.aprobar_rechazar_inscripcion(
  p_id integer,
  p_estado varchar, -- 'aprobado' o 'rechazado'
  p_id_aprobador integer,
  p_motivo_rechazo text DEFAULT NULL
)
RETURNS public.capacitaciones_inscripciones
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_result public.capacitaciones_inscripciones;
BEGIN
  IF p_estado NOT IN ('aprobado', 'rechazado') THEN
    RAISE EXCEPTION 'Estado inválido. Debe ser "aprobado" o "rechazado"';
  END IF;

  UPDATE public.capacitaciones_inscripciones
  SET
    estado = p_estado,
    aprobado_por = p_id_aprobador,
    fecha_aprobacion = now(),
    motivo_rechazo = CASE WHEN p_estado = 'rechazado' THEN p_motivo_rechazo ELSE NULL END,
    updated_at = now()
  WHERE id = p_id;

  SELECT * INTO v_result FROM public.capacitaciones_inscripciones WHERE id = p_id;
  RETURN v_result;
END;
$$;

-- Obtener inscripciones de una capacitación
CREATE OR REPLACE FUNCTION public.obtener_inscripciones_capacitacion(
  p_id_capacitacion integer,
  p_estado varchar DEFAULT NULL
)
RETURNS TABLE (
  id integer,
  id_capacitacion integer,
  id_usuario integer,
  nombre_usuario varchar,
  fecha_inscripcion timestamptz,
  estado varchar,
  asistio boolean,
  calificacion numeric,
  comentarios text,
  aprobado_por integer,
  aprobado_por_nombre varchar,
  fecha_aprobacion timestamptz,
  motivo_rechazo text,
  created_at timestamptz,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    ci.id,
    ci.id_capacitacion,
    ci.id_usuario,
    u.nombre::varchar AS nombre_usuario,
    ci.fecha_inscripcion,
    ci.estado,
    ci.asistio,
    ci.calificacion,
    ci.comentarios,
    ci.aprobado_por,
    u2.nombre::varchar AS aprobado_por_nombre,
    ci.fecha_aprobacion,
    ci.motivo_rechazo,
    ci.created_at,
    ci.updated_at
  FROM public.capacitaciones_inscripciones ci
  JOIN public.usuarios u ON u.id = ci.id_usuario
  LEFT JOIN public.usuarios u2 ON u2.id = ci.aprobado_por
  WHERE ci.id_capacitacion = p_id_capacitacion
    AND (p_estado IS NULL OR ci.estado = p_estado)
  ORDER BY ci.fecha_inscripcion DESC;
END;
$$;

-- Obtener capacitaciones de un usuario
CREATE OR REPLACE FUNCTION public.obtener_capacitaciones_usuario(
  p_id_usuario integer,
  p_estado_inscripcion varchar DEFAULT NULL
)
RETURNS TABLE (
  id integer,
  titulo varchar,
  descripcion text,
  tipo_capacitacion varchar,
  categoria varchar,
  duracion_horas numeric,
  fecha_inicio date,
  fecha_fin date,
  lugar varchar,
  link_virtual text,
  instructor varchar,
  estado varchar,
  estado_inscripcion varchar,
  asistio boolean,
  calificacion numeric,
  fecha_inscripcion timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    c.id,
    c.titulo,
    c.descripcion,
    c.tipo_capacitacion,
