-- Un producto de catálogo (portal / tótem) está hecho con artículos de stock.
-- La lista de precios apunta al producto; no es el producto ni el stock.

CREATE TABLE IF NOT EXISTS public.articulos_empresa_composicion (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_articulo bigint NOT NULL REFERENCES public.articulos_empresa(id) ON DELETE CASCADE,
  id_articulo_stock bigint NOT NULL,
  cantidad numeric NOT NULL DEFAULT 1 CHECK (cantidad > 0),
  codigo_stock text,
  descripcion_stock text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT articulos_empresa_composicion_unica UNIQUE (id_articulo, id_articulo_stock)
);

COMMENT ON TABLE public.articulos_empresa_composicion IS
  'Insumos de stock con los que está hecho un producto de catálogo.';

CREATE INDEX IF NOT EXISTS idx_articulos_empresa_composicion_articulo
  ON public.articulos_empresa_composicion (id_articulo);

ALTER TABLE public.articulos_empresa_composicion ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS articulos_empresa_composicion_all_anon ON public.articulos_empresa_composicion;
CREATE POLICY articulos_empresa_composicion_all_anon
  ON public.articulos_empresa_composicion
  FOR ALL
  TO anon
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS articulos_empresa_composicion_all_auth ON public.articulos_empresa_composicion;
CREATE POLICY articulos_empresa_composicion_all_auth
  ON public.articulos_empresa_composicion
  FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);
