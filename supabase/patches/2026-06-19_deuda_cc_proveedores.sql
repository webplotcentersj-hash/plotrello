CREATE TABLE IF NOT EXISTS public.deuda_cc_proveedores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_codigo varchar(20) NOT NULL DEFAULT '',
  proveedor_nombre text NOT NULL,
  fecha_corte date NOT NULL,
  tipo_comprobante varchar(10) NOT NULL,
  numero_comprobante varchar(50) NOT NULL,
  fecha_comprobante date,
  fecha_vencimiento date,
  total numeric(15,2) NOT NULL DEFAULT 0,
  pagado numeric(15,2) NOT NULL DEFAULT 0,
  deuda numeric(15,2) NOT NULL DEFAULT 0,
  dias_vencido integer,
  total_moneda_origen text,
  total_actualizado numeric(15,2) NOT NULL DEFAULT 0,
  id_proveedor integer REFERENCES public.proveedores(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(proveedor_nombre, tipo_comprobante, numero_comprobante, fecha_comprobante)
);

