CREATE OR REPLACE FUNCTION public.vincular_deuda_cc_proveedores()
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE v_count integer;
BEGIN
  UPDATE public.deuda_cc_proveedores d
  SET id_proveedor = p.id, updated_at = now()
  FROM public.proveedores p
  WHERE d.id_proveedor IS NULL
    AND (
      upper(trim(coalesce(p.razon_social, ''))) = upper(trim(d.proveedor_nombre))
      OR upper(trim(p.nombre)) = upper(trim(d.proveedor_nombre))
      OR upper(trim(p.nombre)) LIKE '%' || upper(trim(split_part(d.proveedor_nombre, ' ', 1))) || '%'
    );
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

