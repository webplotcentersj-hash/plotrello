-- ============================================
-- 1. TABLA DE SOLICITUDES/PERMISOS
-- ============================================
CREATE TABLE IF NOT EXISTS public.solicitudes_permisos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  tipo_solicitud varchar(50) NOT NULL, -- 'turno', 'ausencia', 'vacaciones', 'ropa', 'permiso', 'otro'
  titulo varchar(255) NOT NULL,
  descripcion text,
  fecha_solicitud date NOT NULL DEFAULT CURRENT_DATE,
  fecha_inicio date,
  fecha_fin date,
  dias_solicitados integer,
  estado varchar(50) DEFAULT 'pendiente', -- 'pendiente', 'aprobado', 'rechazado', 'cancelado'
  aprobado_por integer REFERENCES public.usuarios(id),
  fecha_aprobacion timestamptz,
  motivo_rechazo text,
  observaciones text,
  archivo_adjunto_url text, -- Para comprobantes, fotos, etc.
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_solicitudes_usuario ON public.solicitudes_permisos(id_usuario);
CREATE INDEX IF NOT EXISTS idx_solicitudes_estado ON public.solicitudes_permisos(estado);
CREATE INDEX IF NOT EXISTS idx_solicitudes_tipo ON public.solicitudes_permisos(tipo_solicitud);
CREATE INDEX IF NOT EXISTS idx_solicitudes_fecha ON public.solicitudes_permisos(fecha_solicitud);
CREATE INDEX IF NOT EXISTS idx_solicitudes_aprobador ON public.solicitudes_permisos(aprobado_por);

