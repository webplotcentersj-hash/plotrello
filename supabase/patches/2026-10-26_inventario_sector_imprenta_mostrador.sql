-- Inventarios que no existían: Taller de Imprenta y Mostrador.
-- RLS permisivo (anon/authenticated), igual que el pañol de metalúrgica:
-- el cliente usa la anon key y la sesión de la app vive en localStorage.

CREATE TABLE IF NOT EXISTS public.inventario_sector (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sector text NOT NULL,
  categoria text,
  marca text,
  descripcion text,
  ancho numeric,
  largo numeric,
  cantidad_unidades numeric,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT inventario_sector_sector_check CHECK (sector IN ('Taller de Imprenta', 'Mostrador'))
);

COMMENT ON TABLE public.inventario_sector IS 'Insumos de Taller de Imprenta y Mostrador.';

CREATE INDEX IF NOT EXISTS idx_inventario_sector_sector ON public.inventario_sector (sector);

CREATE OR REPLACE FUNCTION public.inventario_sector_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_inventario_sector_updated ON public.inventario_sector;
CREATE TRIGGER trg_inventario_sector_updated
  BEFORE UPDATE ON public.inventario_sector
  FOR EACH ROW
  EXECUTE FUNCTION public.inventario_sector_touch_updated_at();

ALTER TABLE public.inventario_sector ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS inventario_sector_all_anon ON public.inventario_sector;
CREATE POLICY inventario_sector_all_anon
  ON public.inventario_sector
  FOR ALL
  TO anon
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS inventario_sector_all_auth ON public.inventario_sector;
CREATE POLICY inventario_sector_all_auth
  ON public.inventario_sector
  FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);
