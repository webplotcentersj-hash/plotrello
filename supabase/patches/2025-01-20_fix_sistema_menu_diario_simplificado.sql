  p_id_menu integer,
  p_id_usuario integer
)
RETURNS TABLE (
  id integer,
  id_menu integer,
  id_usuario integer,
  id_plato integer,
  nombre_plato varchar(255),
  fecha_seleccion timestamptz,
  created_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
