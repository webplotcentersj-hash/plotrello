-- Función para eliminar menú diario
CREATE OR REPLACE FUNCTION public.eliminar_menu_diario(
  p_id integer
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  DELETE FROM public.menus_diarios WHERE id = p_id;
  RETURN FOUND;
END;
$$;

-- Función para cancelar selección
CREATE OR REPLACE FUNCTION public.cancelar_seleccion_menu(
  p_id_menu integer,
  p_id_usuario integer
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_menu public.menus_diarios;
  v_hora_actual time;
BEGIN
  -- Obtener el menú
  SELECT * INTO v_menu FROM public.menus_diarios WHERE id = p_id_menu;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Menú no encontrado';
  END IF;

  -- Verificar fecha del menú
  IF v_menu.fecha != CURRENT_DATE THEN
    RAISE EXCEPTION 'Solo se puede cancelar la selección del menú del día actual';
  END IF;

  -- Verificar horario (hasta las 9:30 AM)
  v_hora_actual := CURRENT_TIME;
  IF v_hora_actual > '09:30:00'::time THEN
    RAISE EXCEPTION 'El plazo para cancelar la selección ha expirado. Debes hacerlo antes de las 9:30 AM';
  END IF;

  DELETE FROM public.menu_selecciones 
  WHERE id_menu = p_id_menu AND id_usuario = p_id_usuario;
  
  RETURN FOUND;
END;
$$;

