  ON public.menus_diarios FOR INSERT
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.usuarios
      WHERE id = auth.uid()::text::integer
      AND (rol = 'admin' OR rol = 'recursos_humanos')
    )
  );

