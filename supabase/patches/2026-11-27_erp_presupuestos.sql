-- ERP: Presupuesto anual por mes y categoría (ingresos y gastos) para comparar contra lo real.
-- Lo usa /erp/presupuesto. Ejecutar una sola vez en Supabase (SQL editor). Es idempotente.

CREATE TABLE IF NOT EXISTS public.erp_presupuestos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anio smallint NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
  mes smallint NOT NULL CHECK (mes BETWEEN 1 AND 12),
  tipo text NOT NULL CHECK (tipo IN ('ingreso', 'gasto')),
  categoria text NOT NULL CHECK (length(trim(categoria)) > 0),
  monto numeric(15,2) NOT NULL DEFAULT 0 CHECK (monto >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT erp_presupuestos_unico UNIQUE (anio, mes, tipo, categoria)
);

CREATE OR REPLACE FUNCTION public.erp_presupuestos_set_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_erp_presupuestos_updated_at ON public.erp_presupuestos;
CREATE TRIGGER trg_erp_presupuestos_updated_at
BEFORE UPDATE ON public.erp_presupuestos
FOR EACH ROW EXECUTE FUNCTION public.erp_presupuestos_set_updated_at();

ALTER TABLE public.erp_presupuestos ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.erp_presupuestos TO anon, authenticated;
DROP POLICY IF EXISTS "erp_presupuestos acceso" ON public.erp_presupuestos;
CREATE POLICY "erp_presupuestos acceso" ON public.erp_presupuestos
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
GRANT USAGE, SELECT ON SEQUENCE public.erp_presupuestos_id_seq TO anon, authenticated;

NOTIFY pgrst, 'reload schema';
