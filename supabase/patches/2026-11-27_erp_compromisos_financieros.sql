-- ERP: Compromisos financieros (cheques, e-cheqs, pagarés, préstamos, planes de pago...)
-- Cada compromiso tiene una contraparte (cliente, proveedor u otro), un sentido
-- (a cobrar / a pagar) y uno o más vencimientos con fecha e importe.
-- La pantalla /erp/compromisos colorea cada vencimiento según cuánto falta y el cron
-- /api/cron/compromisos-vencimientos manda el resumen diario por Telegram.
-- Ejecutar una sola vez en Supabase (SQL editor). Es idempotente.

CREATE TABLE IF NOT EXISTS public.erp_compromisos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sentido text NOT NULL CHECK (sentido IN ('cobrar', 'pagar')),
  tipo text NOT NULL DEFAULT 'Cheque' CHECK (
    tipo IN ('Cheque', 'E-cheq', 'Pagaré', 'Préstamo', 'Plan de pagos', 'Tarjeta', 'Otro')
  ),
  descripcion text,
  numero text,
  banco text,
  contraparte_tipo text NOT NULL DEFAULT 'otro' CHECK (contraparte_tipo IN ('cliente', 'proveedor', 'otro')),
  id_cliente integer REFERENCES public.clientes(id) ON DELETE SET NULL,
  id_proveedor integer REFERENCES public.proveedores(id) ON DELETE SET NULL,
  contraparte_nombre text,
  -- Cuántos días antes del vencimiento empieza a avisar (amarillo + alerta).
  dias_aviso smallint NOT NULL DEFAULT 7 CHECK (dias_aviso BETWEEN 0 AND 90),
  observaciones text,
  id_usuario integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.erp_compromisos_vencimientos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_compromiso integer NOT NULL REFERENCES public.erp_compromisos(id) ON DELETE CASCADE,
  nro_cuota smallint NOT NULL DEFAULT 1,
  fecha date NOT NULL,
  importe numeric(15,2) NOT NULL CHECK (importe > 0),
  -- N° del cheque de esta cuota cuando cada vencimiento es un cheque distinto.
  numero_cheque text,
  estado text NOT NULL DEFAULT 'Pendiente' CHECK (estado IN ('Pendiente', 'Cumplido', 'Anulado')),
  fecha_cumplido date,
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_erp_compromisos_venc_fecha
  ON public.erp_compromisos_vencimientos (fecha) WHERE estado = 'Pendiente';
CREATE INDEX IF NOT EXISTS idx_erp_compromisos_venc_compromiso
  ON public.erp_compromisos_vencimientos (id_compromiso);

CREATE OR REPLACE FUNCTION public.erp_compromisos_set_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_erp_compromisos_updated_at ON public.erp_compromisos;
CREATE TRIGGER trg_erp_compromisos_updated_at
BEFORE UPDATE ON public.erp_compromisos
FOR EACH ROW EXECUTE FUNCTION public.erp_compromisos_set_updated_at();

DROP TRIGGER IF EXISTS trg_erp_compromisos_venc_updated_at ON public.erp_compromisos_vencimientos;
CREATE TRIGGER trg_erp_compromisos_venc_updated_at
BEFORE UPDATE ON public.erp_compromisos_vencimientos
FOR EACH ROW EXECUTE FUNCTION public.erp_compromisos_set_updated_at();

-- RLS + grants: misma política que el resto del ERP (la app usa anon y authenticated).
ALTER TABLE public.erp_compromisos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.erp_compromisos_vencimientos ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.erp_compromisos TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.erp_compromisos_vencimientos TO anon, authenticated;
DROP POLICY IF EXISTS "erp_compromisos acceso" ON public.erp_compromisos;
CREATE POLICY "erp_compromisos acceso" ON public.erp_compromisos
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "erp_compromisos_vencimientos acceso" ON public.erp_compromisos_vencimientos;
CREATE POLICY "erp_compromisos_vencimientos acceso" ON public.erp_compromisos_vencimientos
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
GRANT USAGE, SELECT ON SEQUENCE public.erp_compromisos_id_seq TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.erp_compromisos_vencimientos_id_seq TO anon, authenticated;

NOTIFY pgrst, 'reload schema';
