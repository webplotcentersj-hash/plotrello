-- 6) Relleno: saldos a favor que solo estaban como texto en la CxC de la factura original --------
INSERT INTO public.saldos_favor_clientes (id_cliente, cliente_nombre, id_nota_credito, id_factura_origen, monto, disponible)
SELECT COALESCE(nc.id_cliente, c.id_cliente),
       COALESCE(NULLIF(nc.cliente_nombre, ''), c.cliente_nombre),
       nc.id,
       nc.id_factura_referencia,
       x.monto,
       x.monto
FROM public.facturas_venta nc
JOIN public.cuentas_por_cobrar c ON c.id_factura = nc.id_factura_referencia
CROSS JOIN LATERAL (
  SELECT replace(m[1], ',', '.')::numeric AS monto
  FROM regexp_matches(
    c.observaciones,
    regexp_replace(nc.tipo_comprobante || ' ' || nc.numero_factura, '([.\-()])', '\\\1', 'g')
      || ': -\$[0-9.,]+ \(saldo a favor del cliente \$([0-9.,]+)\)'
  ) AS m
  LIMIT 1
) x
WHERE nc.tipo_comprobante LIKE 'Nota de Crédito%'
  AND nc.estado_afip = 'Autorizada'
  AND c.observaciones LIKE '%saldo a favor del cliente%'
  AND x.monto > 0
ON CONFLICT (id_nota_credito) DO NOTHING;

