-- 2026-11-24 — Asiento del cobro hecho en la venta (mostrador / caja) al facturarla.
--
-- Problema: al emitir la factura se registra  Debe Deudores por ventas / Haber Ventas + IVA.
-- Si la venta ya se había cobrado en caja, la CxC nace "Pagado" pero no hay pagos_cobros ni
-- asiento de cobro, así que Deudores por ventas nunca se cancela y Caja/Bancos no reflejan el ingreso.
--
-- Ahora:
--  1. crear_asiento_cobro_en_venta(id_factura): Debe Caja (efectivo) o Bancos (resto) / Haber Deudores
--     por lo cobrado en la venta que no está respaldado por pagos_cobros. Idempotente
--     (tipo_origen = 'cobro_venta', id_origen = id de la factura).
--  2. aplicar_efectos_factura lo llama después del asiento de la factura.
--  3. crear_asiento_desde_pago_cobro busca las cuentas por clave_sistema (no por código), es
--     idempotente y no deja asientos desbalanceados si falta una cuenta.
--  4. Relleno: genera el asiento para las facturas ya emitidas que lo necesiten (las de períodos
--     cerrados se informan con NOTICE y se saltean).
--
--  5. Saldo a favor del cliente cuando una nota de crédito supera lo que debía (ya había pagado):
--     queda registrado y se resuelve de 3 formas (se pueden combinar por partes):
--       a) devolverlo en efectivo / transferencia (asiento Debe Deudores / Haber Caja o Bancos),
--       b) dejarlo a cuenta y usarlo al cobrar otra factura del cliente (sin movimiento de dinero),
--       c) pasarlo a su cuenta corriente (movimiento de crédito en cc_cuenta_movimientos).
--     Relleno: los saldos que hasta ahora quedaban solo como texto en la CxC se cargan.
--
-- Requiere 2026-11-17_plan_cuentas_estructura.sql (clave_sistema). Idempotente.

-- 0) Saldos a favor ----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.saldos_favor_clientes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente integer REFERENCES public.clientes(id) ON DELETE SET NULL,
  cliente_nombre text,
  id_nota_credito integer NOT NULL UNIQUE REFERENCES public.facturas_venta(id),
  id_factura_origen integer REFERENCES public.facturas_venta(id),
  monto numeric(14, 2) NOT NULL CHECK (monto > 0),
  disponible numeric(14, 2) NOT NULL CHECK (disponible >= 0 AND disponible <= monto),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_saldos_favor_cliente ON public.saldos_favor_clientes (id_cliente) WHERE disponible > 0;

CREATE TABLE IF NOT EXISTS public.saldos_favor_movimientos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_saldo bigint NOT NULL REFERENCES public.saldos_favor_clientes(id) ON DELETE CASCADE,
  tipo text NOT NULL CHECK (tipo IN ('devolucion', 'aplicacion', 'cuenta_corriente')),
  monto numeric(14, 2) NOT NULL CHECK (monto > 0),
  fecha date NOT NULL DEFAULT CURRENT_DATE,
  metodo_pago text,
  id_cuenta_por_cobrar integer REFERENCES public.cuentas_por_cobrar(id),
  id_asiento integer,
  id_cc_movimiento bigint,
  observaciones text,
  id_usuario integer,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_saldos_favor_mov_saldo ON public.saldos_favor_movimientos (id_saldo);
CREATE INDEX IF NOT EXISTS idx_saldos_favor_mov_cxc ON public.saldos_favor_movimientos (id_cuenta_por_cobrar);

COMMENT ON TABLE public.saldos_favor_clientes IS
  'Saldo a favor del cliente generado por una nota de crédito mayor a lo adeudado. disponible = lo que falta devolver, aplicar o pasar a cuenta corriente.';

-- Lectura desde el front (como el resto de comercial); escrituras solo por las funciones saldo_favor_*
ALTER TABLE public.saldos_favor_clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.saldos_favor_movimientos ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS saldos_favor_clientes_select ON public.saldos_favor_clientes;
CREATE POLICY saldos_favor_clientes_select ON public.saldos_favor_clientes FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS saldos_favor_movimientos_select ON public.saldos_favor_movimientos;
CREATE POLICY saldos_favor_movimientos_select ON public.saldos_favor_movimientos FOR SELECT TO anon, authenticated USING (true);
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.saldos_favor_clientes FROM anon, authenticated;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.saldos_favor_movimientos FROM anon, authenticated;
GRANT SELECT ON public.saldos_favor_clientes, public.saldos_favor_movimientos TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.crear_asiento_cobro_en_venta(p_id_factura integer)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_f public.facturas_venta%ROWTYPE;
  v_cxc public.cuentas_por_cobrar%ROWTYPE;
  v_metodo text;
  v_monto numeric;
  v_asiento_id integer;
  v_cuenta_tesoreria integer;
  v_cuenta_deudores integer;
BEGIN
  SELECT * INTO v_f FROM public.facturas_venta WHERE id = p_id_factura;
  IF NOT FOUND OR v_f.estado <> 'Emitida' OR v_f.tipo_comprobante NOT LIKE 'Factura%' OR v_f.id_venta IS NULL THEN
    RETURN NULL;
  END IF;

  SELECT id INTO v_asiento_id FROM public.asientos_contables
  WHERE tipo_origen = 'cobro_venta' AND id_origen = v_f.id
  ORDER BY id LIMIT 1;
  IF v_asiento_id IS NOT NULL THEN RETURN v_asiento_id; END IF;

  SELECT * INTO v_cxc FROM public.cuentas_por_cobrar WHERE id_factura = v_f.id ORDER BY id LIMIT 1;
  IF NOT FOUND THEN RETURN NULL; END IF;

  -- Lo cobrado que no pasó por pagos_cobros (esos ya tienen su propio asiento)
  -- ni por un saldo a favor aplicado (no movió dinero)
  v_monto := COALESCE(v_cxc.monto_pagado, 0) - COALESCE((
    SELECT SUM(ABS(pc.monto)) FROM public.pagos_cobros pc
    WHERE pc.id_cuenta_por_cobrar = v_cxc.id AND pc.tipo = 'Cobro'
  ), 0) - COALESCE((
    SELECT SUM(m.monto) FROM public.saldos_favor_movimientos m
    WHERE m.id_cuenta_por_cobrar = v_cxc.id AND m.tipo = 'aplicacion'
  ), 0);
  v_monto := round(v_monto, 2);
  IF v_monto <= 0 THEN RETURN NULL; END IF;

  SELECT metodo_pago INTO v_metodo FROM public.ventas WHERE id = v_f.id_venta;

  SELECT id INTO v_cuenta_deudores FROM public.plan_cuentas WHERE clave_sistema = 'deudores_ventas' LIMIT 1;
  IF COALESCE(v_metodo, '') = 'Efectivo' THEN
    SELECT id INTO v_cuenta_tesoreria FROM public.plan_cuentas WHERE clave_sistema = 'caja' LIMIT 1;
  ELSE
    SELECT id INTO v_cuenta_tesoreria FROM public.plan_cuentas WHERE clave_sistema = 'bancos' LIMIT 1;
  END IF;
  IF v_cuenta_tesoreria IS NULL THEN
    SELECT id INTO v_cuenta_tesoreria FROM public.plan_cuentas WHERE clave_sistema = 'caja' LIMIT 1;
  END IF;
  IF v_cuenta_deudores IS NULL OR v_cuenta_tesoreria IS NULL THEN
    RAISE EXCEPTION 'Faltan las cuentas con clave_sistema deudores_ventas / caja / bancos en el plan de cuentas';
  END IF;

  INSERT INTO public.asientos_contables (
    numero_asiento, fecha, concepto, tipo_asiento, id_origen, tipo_origen, total_debe, total_haber, estado
  ) VALUES (
    public.generar_numero_asiento(),
    v_f.fecha_emision,
    'Cobro en la venta #' || v_f.id_venta || ' - ' || v_f.tipo_comprobante || ' ' || v_f.numero_factura
      || ' (' || COALESCE(NULLIF(v_metodo, ''), 'sin medio') || ')',
    'Cobro',
    v_f.id,
    'cobro_venta',
    v_monto,
    v_monto,
    'Contabilizado'
  ) RETURNING id INTO v_asiento_id;

  INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
  VALUES (v_asiento_id, v_cuenta_tesoreria, v_monto, 0, 'Ingreso cobrado en la venta');
  INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
  VALUES (v_asiento_id, v_cuenta_deudores, 0, v_monto, 'Cancelación: ' || COALESCE(v_f.cliente_nombre, 'Cliente'));

  RETURN v_asiento_id;
END;
$$;

REVOKE ALL ON FUNCTION public.crear_asiento_cobro_en_venta(integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.crear_asiento_cobro_en_venta(integer) TO service_role;

-- 2) aplicar_efectos_factura (igual que 2026-09-22 + asiento del cobro en la venta) -----------
CREATE OR REPLACE FUNCTION public.aplicar_efectos_factura(
  p_id_factura integer
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_f public.facturas_venta%ROWTYPE;
  v_cxc public.cuentas_por_cobrar%ROWTYPE;
  v_estado_pago text;
  v_venta_pagado numeric;
  v_total numeric;
  v_pagado numeric := 0;
  v_nuevo_total numeric;
  v_excedente numeric := 0;
  v_out jsonb := '{}'::jsonb;
BEGIN
  SELECT * INTO v_f FROM public.facturas_venta WHERE id = p_id_factura FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Factura % no encontrada', p_id_factura;
  END IF;
  IF v_f.estado <> 'Emitida' OR COALESCE(v_f.estado_afip, '') <> 'Autorizada' THEN
    RAISE EXCEPTION 'El comprobante % no está emitido y autorizado en AFIP', v_f.numero_factura;
  END IF;
  IF v_f.efectos_aplicados_at IS NOT NULL THEN
    RETURN jsonb_build_object('ya_aplicado', true);
  END IF;

  v_total := ABS(COALESCE(v_f.total, 0));

  IF v_f.tipo_comprobante LIKE 'Nota de Crédito%' THEN
    IF v_f.id_factura_referencia IS NOT NULL THEN
      SELECT * INTO v_cxc
      FROM public.cuentas_por_cobrar
      WHERE id_factura = v_f.id_factura_referencia
      ORDER BY id DESC
      LIMIT 1
      FOR UPDATE;

      IF FOUND THEN
        v_nuevo_total := GREATEST(COALESCE(v_cxc.monto_pagado, 0), COALESCE(v_cxc.monto_total, 0) - v_total);
        v_excedente := v_total - (COALESCE(v_cxc.monto_total, 0) - v_nuevo_total);

        UPDATE public.cuentas_por_cobrar SET
          monto_total = v_nuevo_total,
          monto_pendiente = GREATEST(0, v_nuevo_total - COALESCE(monto_pagado, 0)),
          estado = CASE
            WHEN v_nuevo_total - COALESCE(monto_pagado, 0) > 0 THEN estado
            WHEN COALESCE(monto_pagado, 0) > 0 THEN 'Pagado'
            ELSE 'Cancelado'
          END,
          observaciones = concat_ws(
            E'\n',
            NULLIF(observaciones, ''),
            format('%s %s: -$%s', v_f.tipo_comprobante, v_f.numero_factura, to_char(v_total, 'FM999999999990.00'))
              || CASE WHEN v_excedente > 0
                   THEN format(' (saldo a favor del cliente $%s)', to_char(v_excedente, 'FM999999999990.00'))
                   ELSE '' END
          ),
          updated_at = now()
        WHERE id = v_cxc.id;

        IF v_excedente > 0.005 THEN
          INSERT INTO public.saldos_favor_clientes (
            id_cliente, cliente_nombre, id_nota_credito, id_factura_origen, monto, disponible
          ) VALUES (
            COALESCE(v_f.id_cliente, v_cxc.id_cliente), COALESCE(NULLIF(v_f.cliente_nombre, ''), v_cxc.cliente_nombre),
            v_f.id, v_f.id_factura_referencia, round(v_excedente, 2), round(v_excedente, 2)
          )
          ON CONFLICT (id_nota_credito) DO NOTHING;
        END IF;

        v_out := v_out || jsonb_build_object('cxc_ajustada', v_cxc.id, 'saldo_a_favor', v_excedente);
      END IF;
    END IF;
  ELSIF NOT EXISTS (SELECT 1 FROM public.cuentas_por_cobrar WHERE id_factura = v_f.id) THEN
    IF v_f.id_venta IS NOT NULL AND v_f.tipo_comprobante LIKE 'Factura%' THEN
      SELECT estado_pago, monto_pagado INTO v_estado_pago, v_venta_pagado
      FROM public.ventas
      WHERE id = v_f.id_venta;

      IF v_estado_pago = 'Pagado' THEN
        v_pagado := v_total;
      ELSIF v_estado_pago = 'Parcial' THEN
        v_pagado := LEAST(v_total, GREATEST(0, COALESCE(v_venta_pagado, 0)));
      END IF;
    END IF;

    INSERT INTO public.cuentas_por_cobrar (
      id_factura, id_cliente, cliente_nombre, monto_total, monto_pagado, monto_pendiente,
      fecha_emision, fecha_vencimiento, estado, observaciones
    ) VALUES (
      v_f.id,
      v_f.id_cliente,
      COALESCE(NULLIF(v_f.cliente_nombre, ''), 'Cliente'),
      v_total,
      v_pagado,
      v_total - v_pagado,
      v_f.fecha_emision,
      v_f.fecha_vencimiento,
      CASE WHEN v_total - v_pagado <= 0 THEN 'Pagado' WHEN v_pagado > 0 THEN 'Parcial' ELSE 'Pendiente' END,
      CASE WHEN v_pagado > 0 THEN format('Cobrado en la venta #%s', v_f.id_venta) END
    );
    v_out := v_out || jsonb_build_object('cxc_creada', true, 'monto_pagado_venta', v_pagado);
  END IF;

  BEGIN
    PERFORM public.crear_asiento_desde_factura(v_f.id);
  EXCEPTION WHEN OTHERS THEN
    v_out := v_out || jsonb_build_object('asiento_error', SQLERRM);
  END;

  -- Lo cobrado en la venta cancela Deudores contra Caja / Bancos
  BEGIN
    PERFORM public.crear_asiento_cobro_en_venta(v_f.id);
  EXCEPTION WHEN OTHERS THEN
    v_out := v_out || jsonb_build_object('asiento_error', 'Asiento del cobro en la venta: ' || SQLERRM);
  END;

  UPDATE public.facturas_venta SET efectos_aplicados_at = now() WHERE id = v_f.id;
  RETURN v_out || jsonb_build_object('ok', true);
END;
$$;

REVOKE ALL ON FUNCTION public.aplicar_efectos_factura(integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.aplicar_efectos_factura(integer) TO service_role;

-- 3) Cobros / pagos de CxC y CxP: cuentas por clave_sistema, idempotente --------------------
CREATE OR REPLACE FUNCTION public.crear_asiento_desde_pago_cobro(
  p_id_pago_cobro integer
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_pc RECORD;
  v_nombre text;
  v_asiento_id integer;
  v_cuenta_tesoreria integer;
  v_cuenta_contra integer;
  v_monto numeric;
  v_concepto text;
BEGIN
  SELECT * INTO v_pc FROM public.pagos_cobros WHERE id = p_id_pago_cobro;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Pago/Cobro no encontrado: %', p_id_pago_cobro;
  END IF;

  SELECT id INTO v_asiento_id FROM public.asientos_contables
  WHERE tipo_origen = 'pago_cobro' AND id_origen = v_pc.id
  ORDER BY id LIMIT 1;
  IF v_asiento_id IS NOT NULL THEN RETURN v_asiento_id; END IF;

  v_monto := ABS(COALESCE(v_pc.monto, 0));
  IF v_monto <= 0 THEN
    RAISE EXCEPTION 'Monto inválido en Pago/Cobro %', p_id_pago_cobro;
  END IF;

  IF COALESCE(v_pc.metodo_pago, '') = 'Efectivo' THEN
    SELECT id INTO v_cuenta_tesoreria FROM public.plan_cuentas WHERE clave_sistema = 'caja' LIMIT 1;
  ELSE
    SELECT id INTO v_cuenta_tesoreria FROM public.plan_cuentas WHERE clave_sistema = 'bancos' LIMIT 1;
  END IF;
  IF v_cuenta_tesoreria IS NULL THEN
    SELECT id INTO v_cuenta_tesoreria FROM public.plan_cuentas WHERE clave_sistema = 'caja' LIMIT 1;
  END IF;

  IF v_pc.tipo = 'Cobro' THEN
    SELECT id INTO v_cuenta_contra FROM public.plan_cuentas WHERE clave_sistema = 'deudores_ventas' LIMIT 1;
    SELECT cliente_nombre INTO v_nombre FROM public.cuentas_por_cobrar WHERE id = v_pc.id_cuenta_por_cobrar;
    v_concepto := 'Cobro ' || COALESCE(v_nombre, '') || ' (' || COALESCE(v_pc.metodo_pago, '') || ')';
  ELSE
    SELECT id INTO v_cuenta_contra FROM public.plan_cuentas WHERE clave_sistema = 'proveedores' LIMIT 1;
    SELECT proveedor_nombre INTO v_nombre FROM public.cuentas_por_pagar WHERE id = v_pc.id_cuenta_por_pagar;
    v_concepto := 'Pago ' || COALESCE(v_nombre, '') || ' (' || COALESCE(v_pc.metodo_pago, '') || ')';
  END IF;

  -- Sin las dos cuentas el asiento quedaría desbalanceado: mejor no generarlo
  IF v_cuenta_tesoreria IS NULL OR v_cuenta_contra IS NULL THEN
    RAISE EXCEPTION 'Faltan cuentas con clave_sistema (caja/bancos y deudores_ventas/proveedores) en el plan de cuentas';
  END IF;

  INSERT INTO public.asientos_contables (
    numero_asiento, fecha, concepto, tipo_asiento, id_origen, tipo_origen, total_debe, total_haber, estado
  ) VALUES (
    public.generar_numero_asiento(), v_pc.fecha_pago, v_concepto, 'Tesorería', v_pc.id, 'pago_cobro',
    v_monto, v_monto, 'Contabilizado'
  ) RETURNING id INTO v_asiento_id;

  IF v_pc.tipo = 'Cobro' THEN
    INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
    VALUES (v_asiento_id, v_cuenta_tesoreria, v_monto, 0, 'Ingreso por cobro');
    INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
    VALUES (v_asiento_id, v_cuenta_contra, 0, v_monto, 'Cancelación CxC');
  ELSE
    INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
    VALUES (v_asiento_id, v_cuenta_contra, v_monto, 0, 'Cancelación CxP');
    INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
    VALUES (v_asiento_id, v_cuenta_tesoreria, 0, v_monto, 'Egreso por pago');
  END IF;

  RETURN v_asiento_id;
END;
$$;

GRANT EXECUTE ON FUNCTION public.crear_asiento_desde_pago_cobro(integer) TO anon, authenticated, service_role;

-- 4) Relleno: facturas ya emitidas cuyo cobro en la venta no tiene asiento ----------------------
DO $$
DECLARE
  r record;
  v_ok integer := 0;
BEGIN
  FOR r IN
    SELECT f.id, f.numero_factura
    FROM public.facturas_venta f
    JOIN public.cuentas_por_cobrar c ON c.id_factura = f.id
    WHERE f.estado = 'Emitida'
      AND f.tipo_comprobante LIKE 'Factura%'
      AND f.id_venta IS NOT NULL
      AND COALESCE(c.monto_pagado, 0) > 0
      AND NOT EXISTS (
        SELECT 1 FROM public.asientos_contables a WHERE a.tipo_origen = 'cobro_venta' AND a.id_origen = f.id
      )
    ORDER BY f.fecha_emision, f.id
  LOOP
    BEGIN
      IF public.crear_asiento_cobro_en_venta(r.id) IS NOT NULL THEN v_ok := v_ok + 1; END IF;
    EXCEPTION WHEN OTHERS THEN
      RAISE NOTICE 'Factura % (id %): %', r.numero_factura, r.id, SQLERRM;
    END;
  END LOOP;
  RAISE NOTICE 'Asientos de cobro en venta generados: %', v_ok;
END$$;

-- 5) Saldo a favor: devolver / aplicar a otra factura / pasar a cuenta corriente ------------------
CREATE OR REPLACE FUNCTION public._saldo_favor_tomar(p_id_saldo bigint, p_monto numeric)
RETURNS public.saldos_favor_clientes
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_s public.saldos_favor_clientes%ROWTYPE;
BEGIN
  SELECT * INTO v_s FROM public.saldos_favor_clientes WHERE id = p_id_saldo FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Saldo a favor % no encontrado', p_id_saldo; END IF;
  IF p_monto IS NULL OR round(p_monto, 2) <= 0 THEN RAISE EXCEPTION 'El monto debe ser mayor a cero'; END IF;
  IF round(p_monto, 2) > v_s.disponible THEN
    RAISE EXCEPTION 'El monto ($%) supera el saldo disponible ($%)', round(p_monto, 2), v_s.disponible;
  END IF;
  UPDATE public.saldos_favor_clientes
  SET disponible = disponible - round(p_monto, 2), updated_at = now()
  WHERE id = p_id_saldo
  RETURNING * INTO v_s;
  RETURN v_s;
END;
$$;
REVOKE ALL ON FUNCTION public._saldo_favor_tomar(bigint, numeric) FROM PUBLIC, anon, authenticated;

-- a) Devolución en efectivo o transferencia: Debe Deudores por ventas / Haber Caja o Bancos
CREATE OR REPLACE FUNCTION public.saldo_favor_devolver(
  p_actor_id integer,
  p_id_saldo bigint,
  p_monto numeric,
  p_metodo_pago text,
  p_fecha date DEFAULT CURRENT_DATE,
  p_observaciones text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_s public.saldos_favor_clientes%ROWTYPE;
  v_monto numeric := round(p_monto, 2);
  v_fecha date := COALESCE(p_fecha, CURRENT_DATE);
  v_nc text;
  v_cuenta_tesoreria integer;
  v_cuenta_deudores integer;
  v_asiento_id integer;
  v_mov_id bigint;
BEGIN
  IF p_actor_id IS NULL OR NOT public.actor_puede_escribir_comercial(p_actor_id) THEN
    RAISE EXCEPTION 'No autorizado para registrar devoluciones';
  END IF;
  IF COALESCE(p_metodo_pago, '') NOT IN ('Efectivo', 'Transferencia') THEN
    RAISE EXCEPTION 'La devolución es en Efectivo o Transferencia';
  END IF;

  v_s := public._saldo_favor_tomar(p_id_saldo, v_monto);
  SELECT tipo_comprobante || ' ' || numero_factura INTO v_nc FROM public.facturas_venta WHERE id = v_s.id_nota_credito;

  SELECT id INTO v_cuenta_deudores FROM public.plan_cuentas WHERE clave_sistema = 'deudores_ventas' LIMIT 1;
  SELECT id INTO v_cuenta_tesoreria FROM public.plan_cuentas
  WHERE clave_sistema = CASE WHEN p_metodo_pago = 'Efectivo' THEN 'caja' ELSE 'bancos' END LIMIT 1;
  IF v_cuenta_deudores IS NULL OR v_cuenta_tesoreria IS NULL THEN
    RAISE EXCEPTION 'Faltan las cuentas con clave_sistema deudores_ventas / caja / bancos en el plan de cuentas';
  END IF;

  INSERT INTO public.asientos_contables (
    numero_asiento, fecha, concepto, tipo_asiento, id_origen, tipo_origen, total_debe, total_haber, estado
  ) VALUES (
    public.generar_numero_asiento(), v_fecha,
    'Devolución saldo a favor ' || COALESCE(v_s.cliente_nombre, '') || ' (' || COALESCE(v_nc, 'NC') || ', ' || p_metodo_pago || ')',
    'Pago', v_s.id::integer, 'saldo_favor', v_monto, v_monto, 'Contabilizado'
  ) RETURNING id INTO v_asiento_id;
  INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
  VALUES (v_asiento_id, v_cuenta_deudores, v_monto, 0, 'Saldo a favor devuelto: ' || COALESCE(v_s.cliente_nombre, ''));
  INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
  VALUES (v_asiento_id, v_cuenta_tesoreria, 0, v_monto, 'Egreso por devolución (' || p_metodo_pago || ')');

  INSERT INTO public.saldos_favor_movimientos (id_saldo, tipo, monto, fecha, metodo_pago, id_asiento, observaciones, id_usuario)
  VALUES (v_s.id, 'devolucion', v_monto, v_fecha, p_metodo_pago, v_asiento_id, NULLIF(btrim(p_observaciones), ''), p_actor_id)
  RETURNING id INTO v_mov_id;

  RETURN jsonb_build_object('id_movimiento', v_mov_id, 'id_asiento', v_asiento_id, 'disponible', v_s.disponible);
END;
$$;

-- b) Usarlo para cobrar otra factura del mismo cliente (no mueve dinero: no hay asiento,
--    el crédito ya está en Deudores por ventas y compensa la deuda nueva)
CREATE OR REPLACE FUNCTION public.saldo_favor_aplicar(
  p_actor_id integer,
  p_id_saldo bigint,
  p_id_cuenta_por_cobrar integer,
  p_monto numeric
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_s public.saldos_favor_clientes%ROWTYPE;
  v_cxc public.cuentas_por_cobrar%ROWTYPE;
  v_monto numeric := round(p_monto, 2);
  v_nc text;
  v_mov_id bigint;
  v_pendiente numeric;
BEGIN
  IF p_actor_id IS NULL OR NOT public.actor_puede_escribir_comercial(p_actor_id) THEN
    RAISE EXCEPTION 'No autorizado para registrar cobros';
  END IF;

  SELECT * INTO v_cxc FROM public.cuentas_por_cobrar WHERE id = p_id_cuenta_por_cobrar FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Cuenta por cobrar % no encontrada', p_id_cuenta_por_cobrar; END IF;
  IF v_monto > COALESCE(v_cxc.monto_pendiente, 0) + 0.005 THEN
    RAISE EXCEPTION 'El monto ($%) supera lo pendiente de la factura ($%)', v_monto, v_cxc.monto_pendiente;
  END IF;

  SELECT * INTO v_s FROM public.saldos_favor_clientes WHERE id = p_id_saldo;
  IF NOT FOUND THEN RAISE EXCEPTION 'Saldo a favor % no encontrado', p_id_saldo; END IF;
  IF v_s.id_cliente IS NOT NULL AND v_cxc.id_cliente IS NOT NULL AND v_s.id_cliente <> v_cxc.id_cliente THEN
    RAISE EXCEPTION 'El saldo a favor es de otro cliente';
  END IF;

  v_s := public._saldo_favor_tomar(p_id_saldo, v_monto);
  SELECT tipo_comprobante || ' ' || numero_factura INTO v_nc FROM public.facturas_venta WHERE id = v_s.id_nota_credito;

  v_pendiente := GREATEST(0, COALESCE(v_cxc.monto_pendiente, 0) - v_monto);
  UPDATE public.cuentas_por_cobrar SET
    monto_pagado = COALESCE(monto_pagado, 0) + v_monto,
    monto_pendiente = v_pendiente,
    estado = CASE WHEN v_pendiente <= 0.005 THEN 'Pagado' ELSE 'Parcial' END,
    observaciones = concat_ws(E'\n', NULLIF(observaciones, ''),
      format('Saldo a favor aplicado (%s): $%s', COALESCE(v_nc, 'NC'), to_char(v_monto, 'FM999999999990.00'))),
    updated_at = now()
  WHERE id = v_cxc.id;

  INSERT INTO public.saldos_favor_movimientos (id_saldo, tipo, monto, id_cuenta_por_cobrar, id_usuario)
  VALUES (v_s.id, 'aplicacion', v_monto, v_cxc.id, p_actor_id)
  RETURNING id INTO v_mov_id;

  RETURN jsonb_build_object('id_movimiento', v_mov_id, 'disponible', v_s.disponible, 'pendiente_factura', v_pendiente);
END;
$$;

-- c) Pasarlo a la cuenta corriente del cliente (queda como crédito en su libro)
CREATE OR REPLACE FUNCTION public.saldo_favor_a_cuenta_corriente(
  p_actor_id integer,
  p_id_saldo bigint,
  p_monto numeric
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_s public.saldos_favor_clientes%ROWTYPE;
  v_monto numeric := round(p_monto, 2);
  v_nc text;
  v_cc_id bigint;
  v_mov_id bigint;
BEGIN
  IF p_actor_id IS NULL OR NOT public.actor_puede_escribir_comercial(p_actor_id) THEN
    RAISE EXCEPTION 'No autorizado para mover saldos';
  END IF;

  SELECT * INTO v_s FROM public.saldos_favor_clientes WHERE id = p_id_saldo;
  IF NOT FOUND THEN RAISE EXCEPTION 'Saldo a favor % no encontrado', p_id_saldo; END IF;
  IF v_s.id_cliente IS NULL THEN
    RAISE EXCEPTION 'La nota de crédito no está vinculada a un cliente de la ficha';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.clientes_cuenta_corriente cc
    WHERE cc.id_cliente = v_s.id_cliente
      AND public._cc_estado_efectivo(cc.estado, cc.alta_completa) = 'aprobada'
  ) THEN
    RAISE EXCEPTION 'El cliente no tiene cuenta corriente habilitada';
  END IF;

  v_s := public._saldo_favor_tomar(p_id_saldo, v_monto);
  SELECT tipo_comprobante || ' ' || numero_factura INTO v_nc FROM public.facturas_venta WHERE id = v_s.id_nota_credito;

  INSERT INTO public.cc_cuenta_movimientos (
    id_cliente, tipo, fecha, concepto, debe, haber, id_usuario, metadata
  ) VALUES (
    v_s.id_cliente, 'nota_credito', CURRENT_DATE,
    'Saldo a favor por ' || COALESCE(v_nc, 'nota de crédito'), 0, v_monto, p_actor_id,
    jsonb_build_object('id_saldo_favor', v_s.id, 'id_nota_credito', v_s.id_nota_credito)
  ) RETURNING id INTO v_cc_id;

  PERFORM public.cc_sincronizar_estados_ventas_cc(v_s.id_cliente);
  PERFORM public.cc_actualizar_resumen_saldos(v_s.id_cliente);

  INSERT INTO public.saldos_favor_movimientos (id_saldo, tipo, monto, id_cc_movimiento, id_usuario)
  VALUES (v_s.id, 'cuenta_corriente', v_monto, v_cc_id, p_actor_id)
  RETURNING id INTO v_mov_id;

  RETURN jsonb_build_object('id_movimiento', v_mov_id, 'id_cc_movimiento', v_cc_id, 'disponible', v_s.disponible);
END;
$$;

