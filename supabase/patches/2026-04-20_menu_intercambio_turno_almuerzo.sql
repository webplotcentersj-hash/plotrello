-- Intercambio de turno de almuerzo entre dos usuarios con menú del día ya pedido.
-- La solicitud puede hacerse en cualquier hora; al aceptar se intercambian turno_almuerzo en menu_selecciones.

CREATE TABLE IF NOT EXISTS public.menu_intercambios_turno (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_menu integer NOT NULL REFERENCES public.menus_diarios(id) ON DELETE CASCADE,
  id_solicita integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  id_destino integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  estado text NOT NULL DEFAULT 'pendiente'
    CHECK (estado IN ('pendiente', 'aceptada', 'rechazada', 'cancelada')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT menu_intercambios_distintos CHECK (id_solicita <> id_destino)
);

CREATE INDEX IF NOT EXISTS idx_menu_intercambios_menu ON public.menu_intercambios_turno(id_menu);
CREATE INDEX IF NOT EXISTS idx_menu_intercambios_solicita ON public.menu_intercambios_turno(id_solicita);
CREATE INDEX IF NOT EXISTS idx_menu_intercambios_destino ON public.menu_intercambios_turno(id_destino);
CREATE INDEX IF NOT EXISTS idx_menu_intercambios_estado ON public.menu_intercambios_turno(estado);

-- Una solicitud pendiente por par (solicita → destino) en un mismo menú
CREATE UNIQUE INDEX IF NOT EXISTS uq_menu_intercambio_pendiente_par
  ON public.menu_intercambios_turno (id_menu, id_solicita, id_destino)
  WHERE (estado = 'pendiente');

COMMENT ON TABLE public.menu_intercambios_turno IS 'Solicitudes de intercambio de turno de almuerzo (menú diario)';

ALTER TABLE public.menu_intercambios_turno ENABLE ROW LEVEL SECURITY;

