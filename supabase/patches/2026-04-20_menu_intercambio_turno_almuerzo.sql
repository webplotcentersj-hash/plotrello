CREATE OR REPLACE FUNCTION public.solicitar_intercambio_turno_menu(
  p_id_menu integer,
  p_id_solicita integer,
  p_id_destino integer
)
RETURNS public.menu_intercambios_turno
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_menu public.menus_diarios;
  v_fecha_argentina date;
  v_ts_solicita public.menu_selecciones%ROWTYPE;
  v_ts_destino public.menu_selecciones%ROWTYPE;
  v_row public.menu_intercambios_turno%ROWTYPE;
  v_nombre_solicita text;
  v_title text;
  v_desc text;
BEGIN
  IF p_id_solicita IS NULL OR p_id_destino IS NULL OR p_id_menu IS NULL THEN
    RAISE EXCEPTION 'Parámetros inválidos';
  END IF;
  IF p_id_solicita = p_id_destino THEN
    RAISE EXCEPTION 'No podés solicitar intercambio contigo mismo';
  END IF;

  SELECT * INTO v_menu FROM public.menus_diarios WHERE id = p_id_menu;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Menú no encontrado';
  END IF;

  v_fecha_argentina := public.get_argentina_date();
  IF v_menu.fecha <> v_fecha_argentina THEN
    RAISE EXCEPTION 'Solo se pueden intercambiar turnos del menú del día actual';
  END IF;

  SELECT * INTO v_ts_solicita
  FROM public.menu_selecciones
  WHERE id_menu = p_id_menu AND id_usuario = p_id_solicita;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Primero debés tener un pedido de menú para solicitar intercambio';
  END IF;

  SELECT * INTO v_ts_destino
  FROM public.menu_selecciones
  WHERE id_menu = p_id_menu AND id_usuario = p_id_destino;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'La otra persona no tiene pedido de menú para hoy';
  END IF;

  IF v_ts_solicita.turno_almuerzo = v_ts_destino.turno_almuerzo THEN
    RAISE EXCEPTION 'Ya están en el mismo turno de almuerzo';
  END IF;

  INSERT INTO public.menu_intercambios_turno (id_menu, id_solicita, id_destino, estado)
  VALUES (p_id_menu, p_id_solicita, p_id_destino, 'pendiente')
  RETURNING * INTO v_row;

  SELECT nombre INTO v_nombre_solicita FROM public.usuarios WHERE id = p_id_solicita;
  v_title := 'Intercambio de turno de almuerzo';
  v_desc := COALESCE(trim(v_nombre_solicita), 'Un compañero') ||
    ' te pidió intercambiar el turno de almuerzo del menú de hoy. Revisá Menú diario para aceptar o rechazar.';

  BEGIN
    INSERT INTO public.user_notifications (user_id, type, title, description, is_read)
    VALUES (p_id_destino, 'info', v_title, v_desc, false);
  EXCEPTION WHEN undefined_table THEN
    NULL;
  WHEN OTHERS THEN
    NULL;
  END;

  RETURN v_row;
END;
$$;

