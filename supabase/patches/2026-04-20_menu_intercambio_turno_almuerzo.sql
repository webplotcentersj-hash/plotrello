CREATE OR REPLACE FUNCTION public.obtener_intercambios_turno_menu(
  p_id_usuario integer,
  p_id_menu integer DEFAULT NULL
)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN COALESCE(
    (
      SELECT json_agg(row_to_json(q))
      FROM (
        SELECT
          i.id,
          i.id_menu,
          i.id_solicita,
          i.id_destino,
          us.nombre AS nombre_solicita,
          ud.nombre AS nombre_destino,
          i.estado,
          i.created_at,
          i.updated_at
        FROM public.menu_intercambios_turno i
        JOIN public.usuarios us ON us.id = i.id_solicita
        JOIN public.usuarios ud ON ud.id = i.id_destino
        WHERE (p_id_menu IS NULL OR i.id_menu = p_id_menu)
          AND (i.id_solicita = p_id_usuario OR i.id_destino = p_id_usuario)
          AND i.estado = 'pendiente'
        ORDER BY i.created_at DESC
      ) q
    ),
    '[]'::json
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.solicitar_intercambio_turno_menu(integer, integer, integer) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.responder_intercambio_turno_menu(bigint, integer, text) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.obtener_intercambios_turno_menu(integer, integer) TO anon, authenticated;
