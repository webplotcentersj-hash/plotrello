CREATE OR REPLACE FUNCTION public.responder_intercambio_turno_menu(
  p_id_intercambio bigint,
  p_id_usuario integer,
  p_accion text
)
RETURNS public.menu_intercambios_turno
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_row public.menu_intercambios_turno%ROWTYPE;
  v_menu public.menus_diarios;
  v_fecha_argentina date;
  t_sol smallint;
  t_dst smallint;
  v_title text;
  v_desc text;
  v_nombre_destino text;
BEGIN
  IF p_accion IS NULL OR trim(p_accion) = '' THEN
    RAISE EXCEPTION 'Acción inválida';
  END IF;
  p_accion := lower(trim(p_accion));
  IF p_accion NOT IN ('aceptar', 'rechazar', 'cancelar') THEN
    RAISE EXCEPTION 'Acción debe ser aceptar, rechazar o cancelar';
  END IF;

  SELECT * INTO v_row FROM public.menu_intercambios_turno WHERE id = p_id_intercambio FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Solicitud no encontrada';
  END IF;
  IF v_row.estado <> 'pendiente' THEN
    RAISE EXCEPTION 'Esta solicitud ya fue procesada';
  END IF;

  SELECT * INTO v_menu FROM public.menus_diarios WHERE id = v_row.id_menu;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Menú no encontrado';
  END IF;

  v_fecha_argentina := public.get_argentina_date();
  IF v_menu.fecha <> v_fecha_argentina THEN
    RAISE EXCEPTION 'Esta solicitud ya no es válida (no es el día del menú)';
  END IF;

  IF p_accion = 'cancelar' THEN
    IF p_id_usuario <> v_row.id_solicita THEN
      RAISE EXCEPTION 'Solo quien solicitó puede cancelar';
    END IF;
    UPDATE public.menu_intercambios_turno
    SET estado = 'cancelada', updated_at = now()
    WHERE id = p_id_intercambio
    RETURNING * INTO v_row;
    RETURN v_row;
  END IF;

  IF p_accion IN ('aceptar', 'rechazar') THEN
    IF p_id_usuario <> v_row.id_destino THEN
      RAISE EXCEPTION 'Solo quien recibió la solicitud puede aceptar o rechazar';
    END IF;
  END IF;

  IF p_accion = 'rechazar' THEN
    UPDATE public.menu_intercambios_turno
    SET estado = 'rechazada', updated_at = now()
    WHERE id = p_id_intercambio
    RETURNING * INTO v_row;

    BEGIN
      INSERT INTO public.user_notifications (user_id, type, title, description, is_read)
      VALUES (
        v_row.id_solicita,
        'info',
        'Intercambio de turno',
        'Tu solicitud de intercambio de turno de almuerzo fue rechazada.',
        false
      );
    EXCEPTION WHEN undefined_table THEN NULL;
    WHEN OTHERS THEN NULL;
    END;

    RETURN v_row;
  END IF;

  -- aceptar
  SELECT turno_almuerzo INTO t_sol
  FROM public.menu_selecciones
  WHERE id_menu = v_row.id_menu AND id_usuario = v_row.id_solicita;
  SELECT turno_almuerzo INTO t_dst
  FROM public.menu_selecciones
  WHERE id_menu = v_row.id_menu AND id_usuario = v_row.id_destino;

  IF t_sol IS NULL OR t_dst IS NULL THEN
    RAISE EXCEPTION 'Ya no hay selección de menú para uno de los usuarios';
  END IF;

  IF t_sol = t_dst THEN
    UPDATE public.menu_intercambios_turno
    SET estado = 'aceptada', updated_at = now()
    WHERE id = p_id_intercambio
    RETURNING * INTO v_row;
    RETURN v_row;
  END IF;

  -- Intercambio uno a uno: los cupos por turno no cambian (solo se permutan dos personas).

  UPDATE public.menu_selecciones
  SET turno_almuerzo = t_dst, fecha_seleccion = now()
  WHERE id_menu = v_row.id_menu AND id_usuario = v_row.id_solicita;

  UPDATE public.menu_selecciones
  SET turno_almuerzo = t_sol, fecha_seleccion = now()
  WHERE id_menu = v_row.id_menu AND id_usuario = v_row.id_destino;

  UPDATE public.menu_intercambios_turno
  SET estado = 'aceptada', updated_at = now()
  WHERE id = p_id_intercambio
  RETURNING * INTO v_row;

  SELECT nombre INTO v_nombre_destino FROM public.usuarios WHERE id = v_row.id_destino;
  v_title := 'Intercambio de turno confirmado';
  v_desc := COALESCE(trim(v_nombre_destino), 'Tu compañero') ||
    ' aceptó el intercambio. Ya tenés el nuevo turno de almuerzo en el menú del día.';

  BEGIN
    INSERT INTO public.user_notifications (user_id, type, title, description, is_read)
    VALUES (v_row.id_solicita, 'info', v_title, v_desc, false);
  EXCEPTION WHEN undefined_table THEN NULL;
  WHEN OTHERS THEN NULL;
  END;

  RETURN v_row;
END;
$$;

