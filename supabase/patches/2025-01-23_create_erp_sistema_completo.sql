-- ============================================
-- SISTEMA ERP COMPLETO - INTEGRACIÓN CON SISTEMA EXISTENTE
-- ============================================
-- Este script crea la estructura completa para:
-- - Plan de Cuentas Contable
-- - Asientos Contables (Partida Doble)
-- - Facturación (con preparación para AFIP)
-- - Control de Costos por OP
-- - Cuentas por Pagar/Cobrar
-- - Reportes Financieros
-- ============================================

-- ============================================
-- 1. PLAN DE CUENTAS
-- ============================================
CREATE TABLE IF NOT EXISTS public.plan_cuentas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(20) NOT NULL UNIQUE,
  nombre varchar(255) NOT NULL,
  tipo varchar(50) NOT NULL CHECK (
    tipo IN ('Activo', 'Pasivo', 'Patrimonio', 'Ingreso', 'Costo', 'Gasto', 'Cuenta de Orden')
  ),
  nivel integer NOT NULL DEFAULT 1 CHECK (nivel >= 1 AND nivel <= 5),
  cuenta_padre_id integer REFERENCES public.plan_cuentas(id) ON DELETE SET NULL,
  naturaleza varchar(10) NOT NULL CHECK (naturaleza IN ('Deudora', 'Acreedora')),
  activa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_plan_cuentas_codigo ON public.plan_cuentas(codigo);
CREATE INDEX IF NOT EXISTS idx_plan_cuentas_tipo ON public.plan_cuentas(tipo);
CREATE INDEX IF NOT EXISTS idx_plan_cuentas_padre ON public.plan_cuentas(cuenta_padre_id);
CREATE INDEX IF NOT EXISTS idx_plan_cuentas_activa ON public.plan_cuentas(activa);

-- ============================================
-- 2. ASIENTOS CONTABLES
-- ============================================
CREATE TABLE IF NOT EXISTS public.asientos_contables (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_asiento varchar(50) NOT NULL UNIQUE,
  fecha date NOT NULL DEFAULT CURRENT_DATE,
  concepto text NOT NULL,
  tipo_asiento varchar(50) NOT NULL DEFAULT 'Manual' CHECK (
    tipo_asiento IN ('Manual', 'Automático', 'Facturación', 'Compra', 'Pago', 'Cobro', 'Ajuste')
  ),
  id_origen integer, -- ID de la operación que originó el asiento (factura, compra, etc.)
  tipo_origen varchar(50), -- Tipo de origen: 'factura', 'compra', 'op', etc.
  total_debe numeric(15,2) NOT NULL DEFAULT 0,
  total_haber numeric(15,2) NOT NULL DEFAULT 0,
  estado varchar(50) NOT NULL DEFAULT 'Borrador' CHECK (
    estado IN ('Borrador', 'Contabilizado', 'Anulado')
  ),
  id_usuario integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT check_partida_doble CHECK (total_debe = total_haber)
);

CREATE INDEX IF NOT EXISTS idx_asientos_fecha ON public.asientos_contables(fecha);
CREATE INDEX IF NOT EXISTS idx_asientos_tipo ON public.asientos_contables(tipo_asiento);
CREATE INDEX IF NOT EXISTS idx_asientos_estado ON public.asientos_contables(estado);
CREATE INDEX IF NOT EXISTS idx_asientos_origen ON public.asientos_contables(tipo_origen, id_origen);

-- ============================================
-- 3. DETALLE DE ASIENTOS CONTABLES
-- ============================================
CREATE TABLE IF NOT EXISTS public.asientos_detalle (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_asiento integer NOT NULL REFERENCES public.asientos_contables(id) ON DELETE CASCADE,
  id_cuenta integer NOT NULL REFERENCES public.plan_cuentas(id) ON DELETE RESTRICT,
  debe numeric(15,2) NOT NULL DEFAULT 0,
  haber numeric(15,2) NOT NULL DEFAULT 0,
  concepto text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT check_debe_haber CHECK (
    (debe > 0 AND haber = 0) OR (debe = 0 AND haber > 0)
  )
);

CREATE INDEX IF NOT EXISTS idx_asientos_detalle_asiento ON public.asientos_detalle(id_asiento);
CREATE INDEX IF NOT EXISTS idx_asientos_detalle_cuenta ON public.asientos_detalle(id_cuenta);

-- ============================================
-- 4. FACTURAS DE VENTA
-- ============================================
CREATE TABLE IF NOT EXISTS public.facturas_venta (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_factura varchar(50) NOT NULL UNIQUE,
  punto_venta integer NOT NULL DEFAULT 1,
  numero_comprobante integer NOT NULL,
  tipo_comprobante varchar(50) NOT NULL DEFAULT 'Factura A' CHECK (
    tipo_comprobante IN ('Factura A', 'Factura B', 'Factura C', 'Nota de Crédito A', 'Nota de Crédito B', 'Nota de Crédito C', 'Nota de Débito A', 'Nota de Débito B', 'Nota de Débito C')
  ),
  fecha_emision date NOT NULL DEFAULT CURRENT_DATE,
  fecha_vencimiento date,
  id_cliente integer REFERENCES public.clientes(id) ON DELETE SET NULL,
  cliente_nombre varchar(255) NOT NULL,
  cliente_dni_cuit varchar(50),
  cliente_direccion text,
  cliente_condicion_iva varchar(50) CHECK (
    cliente_condicion_iva IN ('Responsable Inscripto', 'Monotributista', 'Exento', 'Consumidor Final', 'No Responsable')
  ),
  id_op integer REFERENCES public.ordenes_trabajo(id) ON DELETE SET NULL,
  numero_op varchar(255),
  id_venta integer REFERENCES public.ventas(id) ON DELETE SET NULL,
  subtotal numeric(15,2) NOT NULL DEFAULT 0,
  descuento numeric(15,2) NOT NULL DEFAULT 0,
  iva numeric(15,2) NOT NULL DEFAULT 0,
  total numeric(15,2) NOT NULL DEFAULT 0,
  estado varchar(50) NOT NULL DEFAULT 'Borrador' CHECK (
    estado IN ('Borrador', 'Emitida', 'Anulada', 'Cancelada')
  ),
  estado_afip varchar(50), -- 'Pendiente', 'Autorizada', 'Rechazada', 'Error', 'Enviando'
  cae varchar(50), -- Código de Autorización Electrónico (AFIP)
  fecha_vencimiento_cae date, -- Fecha de vencimiento del CAE
  numero_cae varchar(50), -- Número de CAE asignado por AFIP
  resultado_afip text, -- Mensaje de resultado de AFIP (si hay error)
  codigo_resultado_afip varchar(10), -- Código de resultado de AFIP
  fecha_autorizacion_afip timestamptz, -- Fecha de autorización por AFIP
  id_asiento_contable integer REFERENCES public.asientos_contables(id) ON DELETE SET NULL,
  id_usuario integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

