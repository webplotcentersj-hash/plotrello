-- Generar número de asiento contable
CREATE OR REPLACE FUNCTION public.generar_numero_asiento()
RETURNS varchar(50) AS $$
DECLARE
  nuevo_numero varchar(50);
  ultimo_numero integer;
BEGIN
  SELECT COALESCE(MAX(CAST(SUBSTRING(numero_asiento FROM '[0-9]+$') AS integer)), 0) + 1
  INTO ultimo_numero
  FROM public.asientos_contables
  WHERE numero_asiento ~ '^AS-[0-9]+$';
  
  nuevo_numero := 'AS-' || LPAD(ultimo_numero::text, 6, '0');
  RETURN nuevo_numero;
END;
$$ LANGUAGE plpgsql;

-- Generar número de factura
CREATE OR REPLACE FUNCTION public.generar_numero_factura(
  p_tipo_comprobante varchar(50),
  p_punto_venta integer DEFAULT 1
)
RETURNS integer AS $$
DECLARE
  nuevo_numero integer;
  config_afip RECORD;
BEGIN
  -- Obtener configuración AFIP
  SELECT * INTO config_afip
  FROM public.configuracion_afip
  WHERE activo = true
  LIMIT 1;
  
  -- Determinar último número según tipo
  IF p_tipo_comprobante LIKE 'Factura A%' OR p_tipo_comprobante LIKE 'Nota de Crédito A%' OR p_tipo_comprobante LIKE 'Nota de Débito A%' THEN
    nuevo_numero := COALESCE(config_afip.ultimo_numero_factura_a, 0) + 1;
  ELSIF p_tipo_comprobante LIKE 'Factura B%' OR p_tipo_comprobante LIKE 'Nota de Crédito B%' OR p_tipo_comprobante LIKE 'Nota de Débito B%' THEN
    nuevo_numero := COALESCE(config_afip.ultimo_numero_factura_b, 0) + 1;
  ELSIF p_tipo_comprobante LIKE 'Factura C%' OR p_tipo_comprobante LIKE 'Nota de Crédito C%' OR p_tipo_comprobante LIKE 'Nota de Débito C%' THEN
    nuevo_numero := COALESCE(config_afip.ultimo_numero_factura_c, 0) + 1;
  ELSE
    nuevo_numero := 1;
  END IF;
  
  RETURN nuevo_numero;
END;
$$ LANGUAGE plpgsql;

-- Crear asiento contable automático desde factura
CREATE OR REPLACE FUNCTION public.crear_asiento_desde_factura(
  p_id_factura integer
)
RETURNS integer AS $$
DECLARE
  v_factura RECORD;
  v_asiento_id integer;
  v_numero_asiento varchar(50);
  v_cuenta_ventas integer;
  v_cuenta_iva integer;
  v_cuenta_clientes integer;
BEGIN
  -- Obtener datos de la factura
  SELECT * INTO v_factura
  FROM public.facturas_venta
  WHERE id = p_id_factura;
  
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Factura no encontrada: %', p_id_factura;
  END IF;
  
  -- Buscar cuentas contables (configurables)
  -- Cuenta de Ventas
  SELECT id INTO v_cuenta_ventas
  FROM public.plan_cuentas
  WHERE codigo = '4.1.1.01' -- Ejemplo: Ventas de productos
  LIMIT 1;
  
  -- Cuenta de IVA Débito Fiscal
  SELECT id INTO v_cuenta_iva
  FROM public.plan_cuentas
  WHERE codigo = '1.1.2.01' -- Ejemplo: IVA Débito Fiscal
  LIMIT 1;
  
  -- Cuenta de Clientes
  SELECT id INTO v_cuenta_clientes
  FROM public.plan_cuentas
  WHERE codigo = '1.1.1.01' -- Ejemplo: Clientes
  LIMIT 1;
  
  -- Generar número de asiento
  v_numero_asiento := public.generar_numero_asiento();
  
  -- Crear asiento contable
  INSERT INTO public.asientos_contables (
    numero_asiento,
    fecha,
    concepto,
    tipo_asiento,
    id_origen,
    tipo_origen,
    total_debe,
    total_haber,
    estado
  ) VALUES (
    v_numero_asiento,
    v_factura.fecha_emision,
    'Factura ' || v_factura.numero_factura || ' - ' || v_factura.cliente_nombre,
    'Facturación',
    v_factura.id,
    'factura',
    v_factura.total,
    v_factura.total,
    'Contabilizado'
  ) RETURNING id INTO v_asiento_id;
  
  -- Crear detalles del asiento
  -- Débito: Clientes
  IF v_cuenta_clientes IS NOT NULL THEN
    INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
    VALUES (v_asiento_id, v_cuenta_clientes, v_factura.total, 0, 'Cliente: ' || v_factura.cliente_nombre);
  END IF;
  
  -- Haber: Ventas
  IF v_cuenta_ventas IS NOT NULL THEN
    INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
    VALUES (v_asiento_id, v_cuenta_ventas, 0, v_factura.subtotal, 'Ventas');
  END IF;
  
  -- Haber: IVA
  IF v_cuenta_iva IS NOT NULL AND v_factura.iva > 0 THEN
    INSERT INTO public.asientos_detalle (id_asiento, id_cuenta, debe, haber, concepto)
    VALUES (v_asiento_id, v_cuenta_iva, 0, v_factura.iva, 'IVA Débito Fiscal');
  END IF;
  
  -- Actualizar factura con ID del asiento
  UPDATE public.facturas_venta
  SET id_asiento_contable = v_asiento_id
  WHERE id = p_id_factura;
  
  RETURN v_asiento_id;
END;
$$ LANGUAGE plpgsql;

-- Calcular costos totales de una OP
CREATE OR REPLACE FUNCTION public.calcular_costos_op(
  p_id_op integer
)
RETURNS TABLE (
  costo_materiales numeric,
  costo_mano_obra numeric,
  costo_gastos_generales numeric,
  costo_total numeric
) AS $$
BEGIN
  RETURN QUERY
  SELECT
    COALESCE(SUM(CASE WHEN tipo_costo = 'Materiales' THEN costo_total ELSE 0 END), 0) as costo_materiales,
    COALESCE(SUM(CASE WHEN tipo_costo = 'Mano de Obra' THEN costo_total ELSE 0 END), 0) as costo_mano_obra,
    COALESCE(SUM(CASE WHEN tipo_costo = 'Gastos Generales' THEN costo_total ELSE 0 END), 0) as costo_gastos_generales,
    COALESCE(SUM(costo_total), 0) as costo_total
  FROM public.costos_op
  WHERE id_op = p_id_op;
END;
$$ LANGUAGE plpgsql;

