-- Trigger para actualizar monto pendiente en cuentas por cobrar
CREATE OR REPLACE FUNCTION public.actualizar_cxc_pendiente()
RETURNS TRIGGER AS $$
BEGIN
  UPDATE public.cuentas_por_cobrar
  SET 
    monto_pagado = (
      SELECT COALESCE(SUM(monto), 0)
      FROM public.pagos_cobros
      WHERE id_cuenta_por_cobrar = NEW.id_cuenta_por_cobrar
        AND tipo = 'Cobro'
    ),
    monto_pendiente = monto_total - (
      SELECT COALESCE(SUM(monto), 0)
      FROM public.pagos_cobros
      WHERE id_cuenta_por_cobrar = NEW.id_cuenta_por_cobrar
        AND tipo = 'Cobro'
    ),
    estado = CASE
      WHEN monto_total - (
        SELECT COALESCE(SUM(monto), 0)
        FROM public.pagos_cobros
        WHERE id_cuenta_por_cobrar = NEW.id_cuenta_por_cobrar
          AND tipo = 'Cobro'
      ) <= 0 THEN 'Pagado'
      WHEN monto_total - (
        SELECT COALESCE(SUM(monto), 0)
        FROM public.pagos_cobros
        WHERE id_cuenta_por_cobrar = NEW.id_cuenta_por_cobrar
          AND tipo = 'Cobro'
      ) < monto_total THEN 'Parcial'
      WHEN fecha_vencimiento < CURRENT_DATE THEN 'Vencido'
      ELSE 'Pendiente'
    END,
    updated_at = now()
  WHERE id = NEW.id_cuenta_por_cobrar;
  
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

