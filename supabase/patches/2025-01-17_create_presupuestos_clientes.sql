-- ============================================
-- SISTEMA DE PRESUPUESTOS DE CLIENTES WEB
-- Los clientes pueden crear presupuestos, guardarlos como borrador y enviarlos a la empresa
-- ============================================

BEGIN;

-- ============================================
-- 1. TABLA DE PRESUPUESTOS DE CLIENTES
-- ============================================
CREATE TABLE IF NOT EXISTS public.presupuestos_clientes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente integer NOT NULL REFERENCES public.clientes(id) ON DELETE CASCADE,
  numero_presupuesto varchar(50) NOT NULL UNIQUE,
  estado varchar(50) NOT NULL DEFAULT 'borrador' CHECK (
    estado IN ('borrador', 'enviado', 'aceptado', 'rechazado', 'cancelado', 'convertido')
  ),
  fecha_creacion timestamptz NOT NULL DEFAULT now(),
  fecha_envio timestamptz,
  fecha_respuesta timestamptz,
  fecha_vencimiento date,
  observaciones_cliente text,
  observaciones_internas text,
  precio_total numeric(10,2) DEFAULT 0,
  id_pedido_asociado integer REFERENCES public.pedidos_clientes(id) ON DELETE SET NULL,
  id_op_asociada integer REFERENCES public.ordenes_trabajo(id) ON DELETE SET NULL,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_presupuestos_cliente ON public.presupuestos_clientes(id_cliente);
CREATE INDEX IF NOT EXISTS idx_presupuestos_numero ON public.presupuestos_clientes(numero_presupuesto);
CREATE INDEX IF NOT EXISTS idx_presupuestos_estado ON public.presupuestos_clientes(estado);
CREATE INDEX IF NOT EXISTS idx_presupuestos_fecha ON public.presupuestos_clientes(fecha_creacion DESC);
CREATE INDEX IF NOT EXISTS idx_presupuestos_pedido ON public.presupuestos_clientes(id_pedido_asociado);
CREATE INDEX IF NOT EXISTS idx_presupuestos_op ON public.presupuestos_clientes(id_op_asociada);

-- ============================================
-- 2. TABLA DE ITEMS DEL PRESUPUESTO
-- ============================================
CREATE TABLE IF NOT EXISTS public.presupuestos_clientes_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_presupuesto integer NOT NULL REFERENCES public.presupuestos_clientes(id) ON DELETE CASCADE,
  id_articulo integer NOT NULL REFERENCES public.articulos_empresa(id) ON DELETE RESTRICT,
  cantidad integer NOT NULL DEFAULT 1,
  precio_unitario numeric(10,2) NOT NULL,
  precio_total numeric(10,2) NOT NULL,
  descripcion_personalizada text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_items_presupuesto ON public.presupuestos_clientes_items(id_presupuesto);
CREATE INDEX IF NOT EXISTS idx_items_articulo_presupuesto ON public.presupuestos_clientes_items(id_articulo);

-- ============================================
-- 3. FUNCIÓN PARA GENERAR NÚMERO ÚNICO DE PRESUPUESTO
-- ============================================
CREATE OR REPLACE FUNCTION public.generar_numero_presupuesto_cliente()
RETURNS varchar(50)
LANGUAGE plpgsql
AS $$
DECLARE
  nuevo_numero varchar(50);
  contador integer;
  año_mes varchar(6);
BEGIN
  -- Formato: PCL-YYYYMM-0001 (reinicia cada mes)
  año_mes := TO_CHAR(CURRENT_DATE, 'YYYYMM');
  
  -- Buscar el último número del mes actual
  SELECT COALESCE(MAX(CAST(SUBSTRING(numero_presupuesto FROM '[0-9]+$') AS INTEGER)), 0) + 1
  INTO contador
  FROM public.presupuestos_clientes
  WHERE numero_presupuesto LIKE 'PCL-' || año_mes || '-%';
  
  nuevo_numero := 'PCL-' || año_mes || '-' || LPAD(contador::text, 4, '0');
  
  -- Verificar que no exista (por si acaso)
  WHILE EXISTS (SELECT 1 FROM public.presupuestos_clientes WHERE numero_presupuesto = nuevo_numero) LOOP
    contador := contador + 1;
    nuevo_numero := 'PCL-' || año_mes || '-' || LPAD(contador::text, 4, '0');
  END LOOP;
  
  RETURN nuevo_numero;
END;
$$;

-- ============================================
-- 4. FUNCIÓN PARA CREAR PRESUPUESTO DE CLIENTE
-- ============================================
CREATE OR REPLACE FUNCTION public.crear_presupuesto_cliente(
  p_id_cliente integer,
  p_items jsonb DEFAULT '[]'::jsonb,
  p_fecha_vencimiento date DEFAULT NULL,
  p_observaciones_cliente text DEFAULT NULL,
  p_estado varchar(50) DEFAULT 'borrador'
)
RETURNS TABLE (
  id integer,
  numero_presupuesto varchar,
  estado varchar,
  precio_total numeric
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  nuevo_presupuesto_id integer;
  numero_presupuesto_generado varchar(50);
  item_record jsonb;
  precio_total_calculado numeric(10,2) := 0;
BEGIN
  -- Validar que el cliente existe, es cliente web y está activo
  IF NOT EXISTS (
    SELECT 1 FROM public.clientes 
    WHERE id = p_id_cliente 
      AND es_cliente_web = true 
      AND activo = true
  ) THEN
    RAISE EXCEPTION 'Cliente no encontrado o inactivo';
  END IF;

  -- Validar estado
  IF p_estado NOT IN ('borrador', 'enviado', 'aceptado', 'rechazado', 'cancelado', 'convertido') THEN
    RAISE EXCEPTION 'Estado inválido: %', p_estado;
  END IF;

  -- Generar número de presupuesto
  numero_presupuesto_generado := public.generar_numero_presupuesto_cliente();

  -- Crear presupuesto
  INSERT INTO public.presupuestos_clientes (
    id_cliente,
    numero_presupuesto,
    estado,
    fecha_vencimiento,
    observaciones_cliente,
    fecha_envio
  ) VALUES (
    p_id_cliente,
    numero_presupuesto_generado,
    p_estado,
    p_fecha_vencimiento,
    p_observaciones_cliente,
    CASE WHEN p_estado = 'enviado' THEN NOW() ELSE NULL END
  )
  RETURNING id INTO nuevo_presupuesto_id;

  -- Procesar items
  FOR item_record IN SELECT * FROM jsonb_array_elements(p_items)
  LOOP
    INSERT INTO public.presupuestos_clientes_items (
      id_presupuesto,
      id_articulo,
      cantidad,
      precio_unitario,
      precio_total,
      descripcion_personalizada
    ) VALUES (
      nuevo_presupuesto_id,
      (item_record->>'id_articulo')::integer,
      COALESCE((item_record->>'cantidad')::integer, 1),
      (item_record->>'precio_unitario')::numeric,
      (item_record->>'precio_total')::numeric,
      item_record->>'descripcion_personalizada'
    );

    precio_total_calculado := precio_total_calculado + ((item_record->>'precio_total')::numeric);
  END LOOP;

  -- Actualizar precio total del presupuesto
  UPDATE public.presupuestos_clientes
  SET precio_total = precio_total_calculado
  WHERE id = nuevo_presupuesto_id;

  RETURN QUERY
  SELECT p.id, p.numero_presupuesto, p.estado, p.precio_total
  FROM public.presupuestos_clientes p
  WHERE p.id = nuevo_presupuesto_id;
END;
$$;

-- ============================================
-- 5. FUNCIÓN PARA ACTUALIZAR PRESUPUESTO DE CLIENTE
-- ============================================
CREATE OR REPLACE FUNCTION public.actualizar_presupuesto_cliente(
  p_id_presupuesto integer,
  p_items jsonb DEFAULT NULL,
  p_fecha_vencimiento date DEFAULT NULL,
  p_observaciones_cliente text DEFAULT NULL,
  p_estado varchar(50) DEFAULT NULL
)
RETURNS TABLE (
  id integer,
  numero_presupuesto varchar,
  estado varchar,
  precio_total numeric
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  item_record jsonb;
  precio_total_calculado numeric(10,2);
  presupuesto_existe boolean;
BEGIN
  -- Verificar que el presupuesto existe
  SELECT EXISTS(SELECT 1 FROM public.presupuestos_clientes WHERE id = p_id_presupuesto)
  INTO presupuesto_existe;
  
  IF NOT presupuesto_existe THEN
    RAISE EXCEPTION 'Presupuesto no encontrado';
  END IF;

  -- Si se proporcionan items, actualizar items
  IF p_items IS NOT NULL THEN
    -- Eliminar items existentes
    DELETE FROM public.presupuestos_clientes_items WHERE id_presupuesto = p_id_presupuesto;
    
    -- Insertar nuevos items
    precio_total_calculado := 0;
    FOR item_record IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
      INSERT INTO public.presupuestos_clientes_items (
        id_presupuesto,
        id_articulo,
        cantidad,
        precio_unitario,
        precio_total,
        descripcion_personalizada
      ) VALUES (
        p_id_presupuesto,
        (item_record->>'id_articulo')::integer,
        COALESCE((item_record->>'cantidad')::integer, 1),
        (item_record->>'precio_unitario')::numeric,
        (item_record->>'precio_total')::numeric,
        item_record->>'descripcion_personalizada'
      );

      precio_total_calculado := precio_total_calculado + ((item_record->>'precio_total')::numeric);
    END LOOP;
  ELSE
    -- Calcular precio total de items existentes
    SELECT COALESCE(SUM(precio_total), 0)
    INTO precio_total_calculado
    FROM public.presupuestos_clientes_items
    WHERE id_presupuesto = p_id_presupuesto;
  END IF;

  -- Actualizar presupuesto
  UPDATE public.presupuestos_clientes
  SET
    fecha_vencimiento = COALESCE(p_fecha_vencimiento, fecha_vencimiento),
    observaciones_cliente = COALESCE(p_observaciones_cliente, observaciones_cliente),
    precio_total = precio_total_calculado,
    estado = COALESCE(p_estado, estado),
    fecha_envio = CASE 
      WHEN p_estado = 'enviado' AND estado != 'enviado' THEN NOW()
      WHEN p_estado != 'enviado' THEN fecha_envio
      ELSE fecha_envio
    END,
    fecha_respuesta = CASE 
      WHEN p_estado IN ('aceptado', 'rechazado') AND estado NOT IN ('aceptado', 'rechazado') THEN NOW()
      ELSE fecha_respuesta
    END,
    updated_at = NOW()
  WHERE id = p_id_presupuesto;

  RETURN QUERY
  SELECT p.id, p.numero_presupuesto, p.estado, p.precio_total
  FROM public.presupuestos_clientes p
  WHERE p.id = p_id_presupuesto;
END;
$$;

-- ============================================
-- 6. FUNCIÓN PARA ENVIAR PRESUPUESTO (cambiar estado a enviado)
-- ============================================
CREATE OR REPLACE FUNCTION public.enviar_presupuesto_cliente(
  p_id_presupuesto integer
)
RETURNS TABLE (
  id integer,
  numero_presupuesto varchar,
  estado varchar,
  fecha_envio timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  UPDATE public.presupuestos_clientes
  SET
    estado = 'enviado',
    fecha_envio = NOW(),
    updated_at = NOW()
  WHERE id = p_id_presupuesto
    AND estado = 'borrador';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Presupuesto no encontrado o no está en estado borrador';
  END IF;

  RETURN QUERY
  SELECT p.id, p.numero_presupuesto, p.estado, p.fecha_envio
  FROM public.presupuestos_clientes p
  WHERE p.id = p_id_presupuesto;
END;
$$;

