-- ============================================
-- 8. FUNCIÓN PARA OBTENER DETALLE DE PRESUPUESTO
-- ============================================
CREATE OR REPLACE FUNCTION public.obtener_detalle_presupuesto_cliente(
  p_id_presupuesto integer
)
RETURNS TABLE (
  presupuesto jsonb,
  items jsonb
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  presupuesto_data jsonb;
  items_data jsonb;
BEGIN
  -- Obtener datos del presupuesto
  SELECT jsonb_build_object(
    'id', p.id,
    'numero_presupuesto', p.numero_presupuesto,
    'estado', p.estado,
    'fecha_creacion', p.fecha_creacion,
    'fecha_envio', p.fecha_envio,
    'fecha_respuesta', p.fecha_respuesta,
    'fecha_vencimiento', p.fecha_vencimiento,
    'precio_total', p.precio_total,
    'observaciones_cliente', p.observaciones_cliente,
    'observaciones_internas', p.observaciones_internas,
    'id_pedido_asociado', p.id_pedido_asociado,
    'id_op_asociada', p.id_op_asociada,
    'cliente', jsonb_build_object(
      'id', c.id,
      'nombre', c.nombre,
      'apellido', c.apellido,
      'empresa', c.empresa,
      'email', c.email,
      'telefono', c.telefono
    )
  )
  INTO presupuesto_data
  FROM public.presupuestos_clientes p
  JOIN public.clientes c ON c.id = p.id_cliente
  WHERE p.id = p_id_presupuesto;

  -- Obtener items del presupuesto
  SELECT jsonb_agg(
    jsonb_build_object(
      'id', i.id,
      'id_articulo', i.id_articulo,
      'articulo', jsonb_build_object(
        'codigo', a.codigo,
        'nombre', a.nombre,
        'descripcion', a.descripcion
      ),
      'cantidad', i.cantidad,
      'precio_unitario', i.precio_unitario,
      'precio_total', i.precio_total,
      'descripcion_personalizada', i.descripcion_personalizada
    )
  )
  INTO items_data
  FROM public.presupuestos_clientes_items i
  JOIN public.articulos_empresa a ON a.id = i.id_articulo
  WHERE i.id_presupuesto = p_id_presupuesto;

  RETURN QUERY
  SELECT
    COALESCE(presupuesto_data, '{}'::jsonb),
    COALESCE(items_data, '[]'::jsonb);
END;
$$;

-- ============================================
-- 9. FUNCIÓN PARA LISTAR PRESUPUESTOS (ADMINISTRACIÓN)
-- ============================================
CREATE OR REPLACE FUNCTION public.listar_presupuestos_clientes_admin(
  p_estado varchar DEFAULT NULL,
  p_id_cliente integer DEFAULT NULL,
  p_fecha_desde date DEFAULT NULL,
  p_fecha_hasta date DEFAULT NULL
)
RETURNS TABLE (
  id integer,
  numero_presupuesto varchar,
  id_cliente integer,
  cliente_nombre varchar,
  cliente_empresa varchar,
  cliente_email varchar,
  estado varchar,
  fecha_creacion timestamptz,
  fecha_envio timestamptz,
  fecha_vencimiento date,
  precio_total numeric,
  id_pedido_asociado integer,
  id_op_asociada integer
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    p.id,
    p.numero_presupuesto,
    p.id_cliente,
    c.nombre as cliente_nombre,
    c.empresa as cliente_empresa,
    c.email as cliente_email,
    p.estado,
    p.fecha_creacion,
    p.fecha_envio,
    p.fecha_vencimiento,
    p.precio_total,
    p.id_pedido_asociado,
    p.id_op_asociada
  FROM public.presupuestos_clientes p
  JOIN public.clientes c ON c.id = p.id_cliente
  WHERE 
    (p_estado IS NULL OR p.estado = p_estado)
    AND (p_id_cliente IS NULL OR p.id_cliente = p_id_cliente)
    AND (p_fecha_desde IS NULL OR p.fecha_creacion::date >= p_fecha_desde)
    AND (p_fecha_hasta IS NULL OR p.fecha_creacion::date <= p_fecha_hasta)
  ORDER BY p.fecha_creacion DESC;
END;
$$;

-- ============================================
-- 10. FUNCIÓN PARA CONVERTIR PRESUPUESTO A PEDIDO
-- ============================================
CREATE OR REPLACE FUNCTION public.convertir_presupuesto_a_pedido_cliente(
  p_id_presupuesto integer,
  p_observaciones_internas text DEFAULT NULL
)
RETURNS TABLE (
  id_pedido integer,
  numero_pedido varchar,
  mensaje text
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  presupuesto_record RECORD;
  nuevo_pedido_id integer;
  numero_pedido_generado varchar(50);
  item_record RECORD;
BEGIN
  -- Obtener datos del presupuesto
  SELECT * INTO presupuesto_record
  FROM public.presupuestos_clientes
  WHERE id = p_id_presupuesto;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Presupuesto no encontrado';
  END IF;

  IF presupuesto_record.estado NOT IN ('enviado', 'aceptado') THEN
    RAISE EXCEPTION 'Solo se pueden convertir presupuestos enviados o aceptados';
  END IF;

  -- Generar número de pedido
  numero_pedido_generado := public.generar_numero_pedido_cliente();

  -- Crear pedido basado en el presupuesto
  INSERT INTO public.pedidos_clientes (
    id_cliente,
    numero_pedido,
    fecha_limite_deseada,
    observaciones_cliente,
    observaciones_internas,
    estado
  ) VALUES (
    presupuesto_record.id_cliente,
    numero_pedido_generado,
    presupuesto_record.fecha_vencimiento,
    presupuesto_record.observaciones_cliente,
    COALESCE(p_observaciones_internas, '') || E'\nConvertido desde presupuesto ' || presupuesto_record.numero_presupuesto,
    'pendiente'
  )
  RETURNING id INTO nuevo_pedido_id;

  -- Copiar items del presupuesto al pedido
  FOR item_record IN
    SELECT * FROM public.presupuestos_clientes_items
    WHERE id_presupuesto = p_id_presupuesto
  LOOP
    INSERT INTO public.pedidos_clientes_items (
      id_pedido,
      id_articulo,
      cantidad,
      precio_unitario,
      precio_total,
      descripcion_personalizada
    ) VALUES (
      nuevo_pedido_id,
      item_record.id_articulo,
      item_record.cantidad,
      item_record.precio_unitario,
      item_record.precio_total,
      item_record.descripcion_personalizada
    );
  END LOOP;

  -- Actualizar precio total del pedido
  UPDATE public.pedidos_clientes
  SET precio_total = presupuesto_record.precio_total
  WHERE id = nuevo_pedido_id;

  -- Actualizar presupuesto para asociarlo con el pedido
  UPDATE public.presupuestos_clientes
  SET
    id_pedido_asociado = nuevo_pedido_id,
    estado = 'convertido',
    updated_at = NOW()
  WHERE id = p_id_presupuesto;

  RETURN QUERY
  SELECT nuevo_pedido_id, numero_pedido_generado, 'Presupuesto convertido exitosamente a pedido ' || numero_pedido_generado;
END;
$$;

