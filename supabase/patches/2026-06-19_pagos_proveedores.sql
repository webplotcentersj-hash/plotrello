CREATE OR REPLACE FUNCTION public.vincular_pagos_proveedores()
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE v_count integer;
BEGIN
  UPDATE public.pagos_proveedores p
  SET id_proveedor = pr.id, updated_at = now()
  FROM public.proveedores pr
  WHERE p.id_proveedor IS NULL
    AND (
      upper(trim(coalesce(pr.razon_social, ''))) = upper(trim(p.proveedor_nombre))
      OR upper(trim(pr.nombre)) = upper(trim(p.proveedor_nombre))
      OR upper(trim(pr.nombre)) LIKE '%' || upper(trim(split_part(p.proveedor_nombre, ' ', 1))) || '%'
    );
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

