CREATE TABLE IF NOT EXISTS public.pagos_proveedores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha date NOT NULL,
  numero_pago varchar(50) NOT NULL,
  numero_recibo varchar(50) NOT NULL DEFAULT '',
  proveedor_nombre text NOT NULL,
  usuario varchar(80),
  monto numeric(15,2) NOT NULL DEFAULT 0,
  id_proveedor integer REFERENCES public.proveedores(id) ON DELETE SET NULL,
  id_pago_cobro integer REFERENCES public.pagos_cobros(id) ON DELETE SET NULL,
  fecha_desde date,
  fecha_hasta date,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(numero_pago, numero_recibo)
);

CREATE INDEX IF NOT EXISTS idx_pagos_proveedores_fecha ON public.pagos_proveedores(fecha DESC);
CREATE INDEX IF NOT EXISTS idx_pagos_proveedores_proveedor ON public.pagos_proveedores(id_proveedor);
CREATE INDEX IF NOT EXISTS idx_pagos_proveedores_nombre ON public.pagos_proveedores(proveedor_nombre);

ALTER TABLE public.pagos_proveedores ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS pagos_proveedores_all ON public.pagos_proveedores;
CREATE POLICY pagos_proveedores_all ON public.pagos_proveedores FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

