-- ============================================
-- PlotAI Sprint Predictions (snapshots + aggregates)
-- ============================================
-- Objetivo:
-- - Guardar histórico real de sprints (snapshots) para que PlotAI "aprenda"
-- - Habilitar predicciones de throughput/ETA basadas en datos reales
-- ============================================

CREATE TABLE IF NOT EXISTS public.plotai_sprint_snapshots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  source varchar(50) NOT NULL DEFAULT 'sprint-optimizer',
  sprint_key varchar(120),
  task_count integer NOT NULL DEFAULT 0,
  completed_count integer NOT NULL DEFAULT 0,
  remaining_count integer NOT NULL DEFAULT 0,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_plotai_sprint_snapshots_created_at
  ON public.plotai_sprint_snapshots(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_plotai_sprint_snapshots_sprint_key
  ON public.plotai_sprint_snapshots(sprint_key);

CREATE INDEX IF NOT EXISTS idx_plotai_sprint_snapshots_payload_gin
  ON public.plotai_sprint_snapshots USING gin (payload);

ALTER TABLE public.plotai_sprint_snapshots ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "plotai_sprint_snapshots_all" ON public.plotai_sprint_snapshots;
CREATE POLICY "plotai_sprint_snapshots_all"
  ON public.plotai_sprint_snapshots
  FOR ALL
  TO anon, authenticated
  USING (true)
  WITH CHECK (true);

-- Vista opcional: últimas métricas (para inspección rápida)
CREATE OR REPLACE VIEW public.v_plotai_sprint_snapshots_latest AS
SELECT
  id,
  created_at,
  source,
  sprint_key,
  task_count,
  completed_count,
  remaining_count
FROM public.plotai_sprint_snapshots
ORDER BY created_at DESC;

