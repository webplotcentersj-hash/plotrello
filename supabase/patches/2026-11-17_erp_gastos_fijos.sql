-- ERP: Gastos fijos (alquiler, servicios, sueldos, seguros, abonos...)
-- Catálogo de gastos recurrentes + vínculo con erp_gastos para marcar cada período como pagado.
-- Requiere: 2026-04-28_erp_gastos.sql (tabla erp_gastos y función set_updated_at_erp_gastos).
-- Ejecutar una sola vez en Supabase (SQL editor). Es idempotente.

CREATE TABLE IF NOT EXISTS public.erp_gastos_fijos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  concepto text NOT NULL,
  categoria text,
  proveedor text,
  proveedor_cuit text,
  monto numeric(14,2) NOT NULL DEFAULT 0 CHECK (monto >= 0),
  moneda text NOT NULL DEFAULT 'ARS',
  frecuencia text NOT NULL DEFAULT 'mensual' CHECK (
    frecuencia IN ('mensual', 'bimestral', 'trimestral', 'semestral', 'anual')
  ),
  -- Períodos en formato YYYY-MM. mes_fin null = sin fecha de fin.
  mes_inicio text NOT NULL CHECK (mes_inicio ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  mes_fin text CHECK (mes_fin IS NULL OR mes_fin ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  dia_vencimiento smallint NOT NULL DEFAULT 10 CHECK (dia_vencimiento BETWEEN 1 AND 31),
  metodo_pago text,
  centro_costo text,
  activo boolean NOT NULL DEFAULT true,
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

DROP TRIGGER IF EXISTS trg_erp_gastos_fijos_updated_at ON public.erp_gastos_fijos;
CREATE TRIGGER trg_erp_gastos_fijos_updated_at
BEFORE UPDATE ON public.erp_gastos_fijos
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at_erp_gastos();

-- Cada pago de un gasto fijo es un gasto normal (aparece en /erp/gastos y sus estadísticas)
-- marcado con el gasto fijo y el período que cubre.
ALTER TABLE public.erp_gastos
  ADD COLUMN IF NOT EXISTS id_gasto_fijo integer REFERENCES public.erp_gastos_fijos(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS periodo_fijo text;

-- Un solo pago por gasto fijo y período.
CREATE UNIQUE INDEX IF NOT EXISTS erp_gastos_fijo_periodo_uidx
  ON public.erp_gastos (id_gasto_fijo, periodo_fijo)
  WHERE id_gasto_fijo IS NOT NULL;

-- RLS + grants: misma política que el resto del ERP (la app usa anon y authenticated).
ALTER TABLE public.erp_gastos_fijos ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.erp_gastos_fijos TO anon, authenticated;
DROP POLICY IF EXISTS "erp_gastos_fijos acceso" ON public.erp_gastos_fijos;
CREATE POLICY "erp_gastos_fijos acceso" ON public.erp_gastos_fijos
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
GRANT USAGE, SELECT ON SEQUENCE public.erp_gastos_fijos_id_seq TO anon, authenticated;

