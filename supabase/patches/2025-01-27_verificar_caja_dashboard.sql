-- Verificar y crear tabla cuentas_por_cobrar si no existe
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'cuentas_por_cobrar') THEN
    CREATE TABLE public.cuentas_por_cobrar (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_factura integer,
      id_cliente integer REFERENCES public.clientes(id) ON DELETE SET NULL,
      cliente_nombre varchar(255) NOT NULL,
      monto_total numeric(15,2) NOT NULL,
      monto_pagado numeric(15,2) NOT NULL DEFAULT 0,
      monto_pendiente numeric(15,2) NOT NULL,
      fecha_emision date NOT NULL,
      fecha_vencimiento date,
      estado varchar(50) NOT NULL DEFAULT 'Pendiente' CHECK (
        estado IN ('Pendiente', 'Parcial', 'Pagado', 'Vencido', 'Cancelado')
      ),
      observaciones text,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    );

    -- Agregar foreign key a facturas_venta solo si la tabla existe
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'facturas_venta') THEN
      ALTER TABLE public.cuentas_por_cobrar 
      ADD CONSTRAINT cuentas_por_cobrar_id_factura_fkey 
      FOREIGN KEY (id_factura) REFERENCES public.facturas_venta(id) ON DELETE CASCADE;
    END IF;

    CREATE INDEX idx_cxc_factura ON public.cuentas_por_cobrar(id_factura);
    CREATE INDEX idx_cxc_cliente ON public.cuentas_por_cobrar(id_cliente);
    CREATE INDEX idx_cxc_estado ON public.cuentas_por_cobrar(estado);
    CREATE INDEX idx_cxc_vencimiento ON public.cuentas_por_cobrar(fecha_vencimiento);
    
    RAISE NOTICE 'Tabla cuentas_por_cobrar creada';
  ELSE
    RAISE NOTICE 'Tabla cuentas_por_cobrar ya existe';
  END IF;
END $$;

