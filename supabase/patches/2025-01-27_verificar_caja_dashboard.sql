-- Verificar y crear función obtener_flujo_caja si no existe
CREATE OR REPLACE FUNCTION public.obtener_flujo_caja(
  p_fecha_desde date,
  p_fecha_hasta date
)
RETURNS TABLE (
  fecha date,
  concepto varchar,
  tipo varchar,
  ingreso numeric,
  egreso numeric,
  saldo_acumulado numeric
) AS $$
DECLARE
  v_saldo_inicial numeric := 0;
  v_saldo_actual numeric := 0;
BEGIN
  
  -- Calcular saldo inicial solo si las tablas existen
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'plan_cuentas')
     AND EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'asientos_contables')
     AND EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'asientos_detalle') THEN
    
    SELECT COALESCE(SUM(
    CASE
      WHEN pc.tipo IN ('Activo') AND pc.codigo LIKE '1.1.1%' THEN
        CASE WHEN pc.naturaleza = 'Deudora' THEN ad.debe - ad.haber ELSE ad.haber - ad.debe END
      ELSE 0
    END
  ), 0) INTO v_saldo_inicial
  FROM public.asientos_detalle ad
  JOIN public.plan_cuentas pc ON pc.id = ad.id_cuenta
  JOIN public.asientos_contables ac ON ac.id = ad.id_asiento
  WHERE ac.fecha < p_fecha_desde
      AND ac.estado = 'Contabilizado'
      AND pc.codigo LIKE '1.1.1%'; -- Caja y Bancos
  END IF;

  v_saldo_actual := v_saldo_inicial;

  -- Retornar movimientos en el período solo si las tablas existen
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'plan_cuentas')
     AND EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'asientos_contables')
     AND EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'asientos_detalle') THEN
    
    RETURN QUERY
  WITH movimientos AS (
    SELECT
      ac.fecha,
      ac.concepto,
      CASE
        WHEN pc.codigo LIKE '4.%' THEN 'Ingreso'
        WHEN pc.codigo LIKE '5.%' OR pc.codigo LIKE '6.%' THEN 'Egreso'
        WHEN pc.codigo LIKE '1.1.1%' THEN 'Movimiento'
        ELSE 'Otro'
      END as tipo_movimiento,
      CASE
        WHEN pc.codigo LIKE '4.%' AND ad.haber > 0 THEN ad.haber
        WHEN pc.codigo LIKE '1.1.1%' AND ad.debe > 0 THEN ad.debe
        ELSE 0
      END as ingreso,
      CASE
        WHEN (pc.codigo LIKE '5.%' OR pc.codigo LIKE '6.%') AND ad.debe > 0 THEN ad.debe
        WHEN pc.codigo LIKE '1.1.1%' AND ad.haber > 0 THEN ad.haber
        ELSE 0
      END as egreso
    FROM public.asientos_detalle ad
    JOIN public.plan_cuentas pc ON pc.id = ad.id_cuenta
    JOIN public.asientos_contables ac ON ac.id = ad.id_asiento
    WHERE ac.fecha >= p_fecha_desde
      AND ac.fecha <= p_fecha_hasta
      AND ac.estado = 'Contabilizado'
      AND (
        pc.codigo LIKE '1.1.1%' OR -- Caja y Bancos
        pc.codigo LIKE '4.%' OR     -- Ingresos
        pc.codigo LIKE '5.%' OR     -- Costos
        pc.codigo LIKE '6.%'        -- Gastos
      )
  )
  SELECT
    m.fecha,
    m.concepto::varchar,
    m.tipo_movimiento::varchar as tipo,
    m.ingreso,
    m.egreso,
    (v_saldo_inicial + SUM(m.ingreso - m.egreso) OVER (ORDER BY m.fecha, m.concepto))::numeric as saldo_acumulado
    FROM movimientos m
    ORDER BY m.fecha, m.concepto;
  ELSE
    -- Si no existen las tablas del ERP, retornar tabla vacía
    RETURN;
  END IF;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION public.obtener_flujo_caja IS 'Obtiene el flujo de caja para un período determinado';

