-- Crear/Actualizar turno
CREATE OR REPLACE FUNCTION public.crear_actualizar_turno(
  p_id_usuario integer,
  p_fecha date,
  p_hora_entrada time,
  p_hora_salida time,
  p_tipo_turno varchar DEFAULT 'normal',
  p_observaciones text DEFAULT NULL
)
RETURNS public.turnos
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_turno_id integer;
  v_result public.turnos;
BEGIN
  INSERT INTO public.turnos (
    id_usuario, fecha, hora_entrada, hora_salida, tipo_turno, observaciones
  )
  VALUES (
    p_id_usuario, p_fecha, p_hora_entrada, p_hora_salida, p_tipo_turno, p_observaciones
  )
  ON CONFLICT (id_usuario, fecha) DO UPDATE
  SET
    hora_entrada = EXCLUDED.hora_entrada,
    hora_salida = EXCLUDED.hora_salida,
    tipo_turno = EXCLUDED.tipo_turno,
    observaciones = EXCLUDED.observaciones,
    updated_at = now()
  RETURNING id INTO v_turno_id;

  SELECT * INTO v_result FROM public.turnos WHERE id = v_turno_id;
  RETURN v_result;
END;
$$;

-- Listar turnos por rango de fechas
CREATE OR REPLACE FUNCTION public.obtener_turnos(
  p_id_usuario integer DEFAULT NULL,
  p_fecha_desde date DEFAULT NULL,
  p_fecha_hasta date DEFAULT NULL
)
RETURNS TABLE (
  id integer,
  id_usuario integer,
  nombre_usuario varchar,
  fecha date,
  hora_entrada time,
  hora_salida time,
  tipo_turno varchar,
  observaciones text,
  created_at timestamptz,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    t.id,
    t.id_usuario,
    u.nombre::varchar AS nombre_usuario,
    t.fecha,
    t.hora_entrada,
    t.hora_salida,
    t.tipo_turno,
    t.observaciones,
    t.created_at,
    t.updated_at
  FROM public.turnos t
  JOIN public.usuarios u ON u.id = t.id_usuario
  WHERE
    (p_id_usuario IS NULL OR t.id_usuario = p_id_usuario)
    AND (p_fecha_desde IS NULL OR t.fecha >= p_fecha_desde)
    AND (p_fecha_hasta IS NULL OR t.fecha <= p_fecha_hasta)
  ORDER BY t.fecha DESC, u.nombre;
END;
$$;

-- Eliminar turno
CREATE OR REPLACE FUNCTION public.eliminar_turno(p_id integer)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  DELETE FROM public.turnos WHERE id = p_id;
  RETURN FOUND;
END;
$$;

