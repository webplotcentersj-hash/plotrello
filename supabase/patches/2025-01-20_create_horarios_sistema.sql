-- Registrar entrada
CREATE OR REPLACE FUNCTION public.registrar_entrada(
  p_id_usuario integer,
  p_fecha date DEFAULT NULL,
  p_hora_entrada timestamptz DEFAULT NULL
)
RETURNS public.asistencia
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_fecha date;
  v_hora_entrada timestamptz;
  v_asistencia_id integer;
  v_result public.asistencia;
BEGIN
  v_fecha := COALESCE(p_fecha, CURRENT_DATE);
  v_hora_entrada := COALESCE(p_hora_entrada, now());

  INSERT INTO public.asistencia (id_usuario, fecha, hora_entrada)
  VALUES (p_id_usuario, v_fecha, v_hora_entrada)
  ON CONFLICT (id_usuario, fecha) DO UPDATE
  SET
    hora_entrada = EXCLUDED.hora_entrada,
    updated_at = now()
  RETURNING id INTO v_asistencia_id;

  SELECT * INTO v_result FROM public.asistencia WHERE id = v_asistencia_id;
  RETURN v_result;
END;
$$;

-- Registrar salida
CREATE OR REPLACE FUNCTION public.registrar_salida(
  p_id_usuario integer,
  p_fecha date DEFAULT NULL,
  p_hora_salida timestamptz DEFAULT NULL
)
RETURNS public.asistencia
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_fecha date;
  v_hora_salida timestamptz;
  v_horas_trabajadas numeric;
  v_asistencia_id integer;
  v_result public.asistencia;
BEGIN
  v_fecha := COALESCE(p_fecha, CURRENT_DATE);
  v_hora_salida := COALESCE(p_hora_salida, now());

  -- Calcular horas trabajadas
  SELECT EXTRACT(EPOCH FROM (v_hora_salida - hora_entrada)) / 3600
  INTO v_horas_trabajadas
  FROM public.asistencia
  WHERE id_usuario = p_id_usuario AND fecha = v_fecha;

  INSERT INTO public.asistencia (id_usuario, fecha, hora_salida, horas_trabajadas)
  VALUES (p_id_usuario, v_fecha, v_hora_salida, v_horas_trabajadas)
  ON CONFLICT (id_usuario, fecha) DO UPDATE
  SET
    hora_salida = EXCLUDED.hora_salida,
    horas_trabajadas = EXCLUDED.horas_trabajadas,
    updated_at = now()
  RETURNING id INTO v_asistencia_id;

  SELECT * INTO v_result FROM public.asistencia WHERE id = v_asistencia_id;
  RETURN v_result;
END;
$$;

