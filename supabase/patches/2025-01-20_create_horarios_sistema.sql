-- Crear ausencia
CREATE OR REPLACE FUNCTION public.crear_ausencia(
  p_id_usuario integer,
  p_tipo_ausencia varchar,
  p_fecha_inicio date,
  p_fecha_fin date,
  p_motivo text DEFAULT NULL,
  p_observaciones text DEFAULT NULL
)
RETURNS public.ausencias
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_ausencia_id integer;
  v_dias integer;
  v_result public.ausencias;
BEGIN
  -- Calcular días
  v_dias := p_fecha_fin - p_fecha_inicio + 1;

  INSERT INTO public.ausencias (
    id_usuario, tipo_ausencia, fecha_inicio, fecha_fin, dias, motivo, observaciones
  )
  VALUES (
    p_id_usuario, p_tipo_ausencia, p_fecha_inicio, p_fecha_fin, v_dias, p_motivo, p_observaciones
  )
  RETURNING id INTO v_ausencia_id;

  SELECT * INTO v_result FROM public.ausencias WHERE id = v_ausencia_id;
  RETURN v_result;
END;
$$;

-- Listar ausencias
CREATE OR REPLACE FUNCTION public.obtener_ausencias(
  p_id_usuario integer DEFAULT NULL,
  p_fecha_desde date DEFAULT NULL,
  p_fecha_hasta date DEFAULT NULL,
  p_estado varchar DEFAULT NULL
)
RETURNS TABLE (
  id integer,
  id_usuario integer,
  nombre_usuario varchar,
  tipo_ausencia varchar,
  fecha_inicio date,
  fecha_fin date,
  dias integer,
  motivo text,
  estado varchar,
  aprobado_por integer,
  aprobado_por_nombre varchar,
  fecha_aprobacion timestamptz,
  observaciones text,
  created_at timestamptz,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    a.id,
    a.id_usuario,
    u.nombre::varchar AS nombre_usuario,
    a.tipo_ausencia,
    a.fecha_inicio,
    a.fecha_fin,
    a.dias,
    a.motivo,
    a.estado,
    a.aprobado_por,
    u2.nombre::varchar AS aprobado_por_nombre,
    a.fecha_aprobacion,
    a.observaciones,
    a.created_at,
    a.updated_at
  FROM public.ausencias a
  JOIN public.usuarios u ON u.id = a.id_usuario
  LEFT JOIN public.usuarios u2 ON u2.id = a.aprobado_por
  WHERE
    (p_id_usuario IS NULL OR a.id_usuario = p_id_usuario)
    AND (p_fecha_desde IS NULL OR a.fecha_fin >= p_fecha_desde)
    AND (p_fecha_hasta IS NULL OR a.fecha_inicio <= p_fecha_hasta)
    AND (p_estado IS NULL OR a.estado = p_estado)
  ORDER BY a.fecha_inicio DESC;
END;
$$;

-- Aprobar/Rechazar ausencia
CREATE OR REPLACE FUNCTION public.aprobar_rechazar_ausencia(
  p_id integer,
  p_estado varchar,
  p_id_aprobador integer,
  p_observaciones text DEFAULT NULL
)
RETURNS public.ausencias
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_result public.ausencias;
BEGIN
  UPDATE public.ausencias
  SET
    estado = p_estado,
    aprobado_por = p_id_aprobador,
    fecha_aprobacion = CASE WHEN p_estado = 'aprobado' THEN now() ELSE NULL END,
    observaciones = COALESCE(p_observaciones, observaciones),
    updated_at = now()
  WHERE id = p_id;

  SELECT * INTO v_result FROM public.ausencias WHERE id = p_id;
  RETURN v_result;
END;
$$;

-- Eliminar ausencia
CREATE OR REPLACE FUNCTION public.eliminar_ausencia(p_id integer)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  DELETE FROM public.ausencias WHERE id = p_id;
  RETURN FOUND;
END;
$$;

