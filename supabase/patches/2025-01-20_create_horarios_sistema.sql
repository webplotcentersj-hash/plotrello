-- ============================================
-- SISTEMA DE GESTIÓN DE HORARIOS Y TURNOS
-- ============================================

BEGIN;

-- ============================================
-- 1. TABLA DE HORARIOS DE EMPLEADOS
-- ============================================
CREATE TABLE IF NOT EXISTS public.horarios_empleados (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  tipo_horario varchar(50) NOT NULL DEFAULT 'fijo', -- 'fijo', 'flexible', 'turnos'
  dia_semana integer, -- 0=Domingo, 1=Lunes, ..., 6=Sábado (NULL para horarios flexibles)
  hora_entrada time,
  hora_salida time,
  horas_semanales numeric(5,2), -- Para horarios flexibles
  activo boolean DEFAULT true,
  fecha_inicio date,
  fecha_fin date, -- NULL para horarios indefinidos
  observaciones text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_horarios_usuario ON public.horarios_empleados(id_usuario);
CREATE INDEX IF NOT EXISTS idx_horarios_activo ON public.horarios_empleados(activo);
CREATE INDEX IF NOT EXISTS idx_horarios_dia ON public.horarios_empleados(dia_semana);

-- ============================================
-- 2. TABLA DE TURNOS ASIGNADOS
-- ============================================
CREATE TABLE IF NOT EXISTS public.turnos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  fecha date NOT NULL,
  hora_entrada time NOT NULL,
  hora_salida time NOT NULL,
  tipo_turno varchar(50) DEFAULT 'normal', -- 'normal', 'extra', 'nocturno'
  observaciones text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  UNIQUE(id_usuario, fecha)
);

CREATE INDEX IF NOT EXISTS idx_turnos_usuario ON public.turnos(id_usuario);
CREATE INDEX IF NOT EXISTS idx_turnos_fecha ON public.turnos(fecha);
CREATE INDEX IF NOT EXISTS idx_turnos_usuario_fecha ON public.turnos(id_usuario, fecha);

-- ============================================
-- 3. TABLA DE AUSENCIAS
-- ============================================
CREATE TABLE IF NOT EXISTS public.ausencias (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  tipo_ausencia varchar(50) NOT NULL, -- 'vacaciones', 'licencia', 'inasistencia', 'permiso', 'enfermedad'
  fecha_inicio date NOT NULL,
  fecha_fin date NOT NULL,
  dias integer, -- Calculado automáticamente
  motivo text,
  estado varchar(50) DEFAULT 'pendiente', -- 'pendiente', 'aprobado', 'rechazado'
  aprobado_por integer REFERENCES public.usuarios(id),
  fecha_aprobacion timestamptz,
  observaciones text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ausencias_usuario ON public.ausencias(id_usuario);
CREATE INDEX IF NOT EXISTS idx_ausencias_fecha ON public.ausencias(fecha_inicio, fecha_fin);
CREATE INDEX IF NOT EXISTS idx_ausencias_estado ON public.ausencias(estado);

-- ============================================
-- 4. TABLA DE ASISTENCIA (ENTRADA/SALIDA)
-- ============================================
CREATE TABLE IF NOT EXISTS public.asistencia (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  fecha date NOT NULL,
  hora_entrada timestamptz,
  hora_salida timestamptz,
  horas_trabajadas numeric(5,2), -- Calculado automáticamente
  tipo_registro varchar(50) DEFAULT 'normal', -- 'normal', 'tarde', 'ausente', 'justificado'
  observaciones text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  UNIQUE(id_usuario, fecha)
);

CREATE INDEX IF NOT EXISTS idx_asistencia_usuario ON public.asistencia(id_usuario);
CREATE INDEX IF NOT EXISTS idx_asistencia_fecha ON public.asistencia(fecha);
CREATE INDEX IF NOT EXISTS idx_asistencia_usuario_fecha ON public.asistencia(id_usuario, fecha);

-- ============================================
-- 5. FUNCIONES PARA HORARIOS
-- ============================================

-- Crear/Actualizar horario
CREATE OR REPLACE FUNCTION public.crear_actualizar_horario(
  p_id_usuario integer,
  p_tipo_horario varchar,
  p_dia_semana integer DEFAULT NULL,
  p_hora_entrada time DEFAULT NULL,
  p_hora_salida time DEFAULT NULL,
  p_horas_semanales numeric DEFAULT NULL,
  p_fecha_inicio date DEFAULT NULL,
  p_fecha_fin date DEFAULT NULL,
  p_observaciones text DEFAULT NULL,
  p_activo boolean DEFAULT true
)
RETURNS public.horarios_empleados
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_horario_id integer;
  v_result public.horarios_empleados;
BEGIN
  INSERT INTO public.horarios_empleados (
    id_usuario, tipo_horario, dia_semana, hora_entrada, hora_salida,
    horas_semanales, fecha_inicio, fecha_fin, observaciones, activo
  )
  VALUES (
    p_id_usuario, p_tipo_horario, p_dia_semana, p_hora_entrada, p_hora_salida,
    p_horas_semanales, p_fecha_inicio, p_fecha_fin, p_observaciones, p_activo
  )
  RETURNING id INTO v_horario_id;

  SELECT * INTO v_result FROM public.horarios_empleados WHERE id = v_horario_id;
  RETURN v_result;
END;
$$;

-- Listar horarios de un usuario
CREATE OR REPLACE FUNCTION public.obtener_horarios_usuario(p_id_usuario integer)
RETURNS SETOF public.horarios_empleados
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT * FROM public.horarios_empleados
  WHERE id_usuario = p_id_usuario
  ORDER BY dia_semana NULLS LAST, fecha_inicio DESC;
END;
$$;

-- Eliminar horario
CREATE OR REPLACE FUNCTION public.eliminar_horario(p_id integer)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  DELETE FROM public.horarios_empleados WHERE id = p_id;
  RETURN FOUND;
END;
$$;

