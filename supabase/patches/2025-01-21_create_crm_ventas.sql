-- Sistema CRM de Ventas
-- Integrado con OPs, ventas y stock
-- Acceso: mostrador y admin

BEGIN;

-- ============================================
-- 1. TABLA DE OPORTUNIDADES DE VENTA
-- ============================================
CREATE TABLE IF NOT EXISTS public.oportunidades_venta (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_oportunidad varchar(50) NOT NULL UNIQUE,
  cliente_nombre varchar(255) NOT NULL,
  cliente_telefono varchar(50),
  cliente_email varchar(255),
  cliente_dni_cuit varchar(50),
  cliente_empresa varchar(255),
  cliente_direccion text,
  descripcion text,
  valor_estimado numeric(10,2),
  probabilidad_cierre integer DEFAULT 50 CHECK (probabilidad_cierre >= 0 AND probabilidad_cierre <= 100),
  etapa varchar(50) NOT NULL DEFAULT 'Prospecto' CHECK (
    etapa IN ('Prospecto', 'Calificación', 'Propuesta', 'Negociación', 'Cerrado', 'Perdido')
  ),
  fecha_cierre_estimada date,
  id_vendedor integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  nombre_vendedor varchar(100) NOT NULL,
  id_op integer REFERENCES public.ordenes_trabajo(id) ON DELETE SET NULL,
  numero_op varchar(255),
  observaciones text,
  activo boolean DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_oportunidades_vendedor ON public.oportunidades_venta(id_vendedor);
CREATE INDEX IF NOT EXISTS idx_oportunidades_etapa ON public.oportunidades_venta(etapa);
CREATE INDEX IF NOT EXISTS idx_oportunidades_cliente ON public.oportunidades_venta(cliente_nombre);
CREATE INDEX IF NOT EXISTS idx_oportunidades_fecha_cierre ON public.oportunidades_venta(fecha_cierre_estimada);
CREATE INDEX IF NOT EXISTS idx_oportunidades_activo ON public.oportunidades_venta(activo);
CREATE INDEX IF NOT EXISTS idx_oportunidades_op ON public.oportunidades_venta(id_op);

-- ============================================
-- 2. TABLA DE VENTAS CONCRETADAS
-- ============================================
CREATE TABLE IF NOT EXISTS public.ventas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_venta varchar(50) NOT NULL UNIQUE,
  id_oportunidad integer REFERENCES public.oportunidades_venta(id) ON DELETE SET NULL,
  cliente_nombre varchar(255) NOT NULL,
  cliente_telefono varchar(50),
  cliente_email varchar(255),
  cliente_dni_cuit varchar(50),
  cliente_empresa varchar(255),
  cliente_direccion text,
  id_op integer NOT NULL REFERENCES public.ordenes_trabajo(id) ON DELETE CASCADE,
  numero_op varchar(255) NOT NULL,
  valor_total numeric(10,2) NOT NULL,
  metodo_pago varchar(50) CHECK (
    metodo_pago IN ('Efectivo', 'Transferencia', 'Tarjeta', 'Cheque', 'Cuenta Corriente', 'Otro')
  ),
  estado_pago varchar(50) NOT NULL DEFAULT 'Pendiente' CHECK (
    estado_pago IN ('Pendiente', 'Parcial', 'Pagado', 'Cancelado')
  ),
  fecha_venta date NOT NULL DEFAULT CURRENT_DATE,
  id_vendedor integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  nombre_vendedor varchar(100) NOT NULL,
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ventas_oportunidad ON public.ventas(id_oportunidad);
CREATE INDEX IF NOT EXISTS idx_ventas_op ON public.ventas(id_op);
CREATE INDEX IF NOT EXISTS idx_ventas_vendedor ON public.ventas(id_vendedor);
CREATE INDEX IF NOT EXISTS idx_ventas_fecha ON public.ventas(fecha_venta);
CREATE INDEX IF NOT EXISTS idx_ventas_estado_pago ON public.ventas(estado_pago);
CREATE INDEX IF NOT EXISTS idx_ventas_cliente ON public.ventas(cliente_nombre);

-- ============================================
-- 3. TABLA DE SEGUIMIENTOS DE OPORTUNIDADES
-- ============================================
CREATE TABLE IF NOT EXISTS public.seguimientos_venta (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_oportunidad integer NOT NULL REFERENCES public.oportunidades_venta(id) ON DELETE CASCADE,
  tipo_seguimiento varchar(50) NOT NULL CHECK (
    tipo_seguimiento IN ('Llamada', 'Email', 'Reunión', 'WhatsApp', 'Visita', 'Propuesta', 'Otro')
  ),
  descripcion text NOT NULL,
  fecha_seguimiento timestamptz NOT NULL DEFAULT now(),
  proxima_accion text,
  fecha_proxima_accion date,
  id_usuario integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  nombre_usuario varchar(100) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_seguimientos_oportunidad ON public.seguimientos_venta(id_oportunidad);
CREATE INDEX IF NOT EXISTS idx_seguimientos_fecha ON public.seguimientos_venta(fecha_seguimiento);
CREATE INDEX IF NOT EXISTS idx_seguimientos_usuario ON public.seguimientos_venta(id_usuario);

-- ============================================
-- 4. TABLA DE ITEMS DE VENTA
-- ============================================
CREATE TABLE IF NOT EXISTS public.ventas_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venta integer NOT NULL REFERENCES public.ventas(id) ON DELETE CASCADE,
  id_articulo_stock integer, -- ID del artículo en la base de stock
  codigo_articulo varchar(100),
  descripcion text NOT NULL,
  cantidad numeric(10,3) NOT NULL DEFAULT 1.000,
  precio_unitario numeric(10,2) NOT NULL,
  precio_total numeric(10,2) NOT NULL,
  descuento numeric(10,2) DEFAULT 0,
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ventas_items_venta ON public.ventas_items(id_venta);
CREATE INDEX IF NOT EXISTS idx_ventas_items_articulo ON public.ventas_items(id_articulo_stock);

