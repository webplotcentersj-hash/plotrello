-- Función para crear oportunidad de venta
CREATE OR REPLACE FUNCTION public.crear_oportunidad_venta(
  p_cliente_nombre varchar(255),
  p_cliente_telefono varchar(50) DEFAULT NULL,
  p_cliente_email varchar(255) DEFAULT NULL,
  p_cliente_dni_cuit varchar(50) DEFAULT NULL,
  p_cliente_empresa varchar(255) DEFAULT NULL,
  p_cliente_direccion text DEFAULT NULL,
  p_descripcion text DEFAULT NULL,
  p_valor_estimado numeric(10,2) DEFAULT NULL,
  p_probabilidad_cierre integer DEFAULT 50,
  p_etapa varchar(50) DEFAULT 'Prospecto',
  p_fecha_cierre_estimada date DEFAULT NULL,
  p_id_vendedor integer,
  p_nombre_vendedor varchar(100),
  p_observaciones text DEFAULT NULL
)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_id integer;
  v_numero_oportunidad varchar(50);
  v_result json;
BEGIN
  -- Generar número de oportunidad
  v_numero_oportunidad := 'OPP-' || TO_CHAR(now(), 'YYYYMMDD') || '-' || LPAD(
    (COALESCE((SELECT MAX(id) FROM public.oportunidades_venta), 0) + 1)::text,
    4,
    '0'
  );

  -- Insertar oportunidad
  INSERT INTO public.oportunidades_venta (
    numero_oportunidad,
    cliente_nombre,
    cliente_telefono,
    cliente_email,
    cliente_dni_cuit,
    cliente_empresa,
    cliente_direccion,
    descripcion,
    valor_estimado,
    probabilidad_cierre,
    etapa,
    fecha_cierre_estimada,
    id_vendedor,
    nombre_vendedor,
    observaciones
  ) VALUES (
    v_numero_oportunidad,
    p_cliente_nombre,
    p_cliente_telefono,
    p_cliente_email,
    p_cliente_dni_cuit,
    p_cliente_empresa,
    p_cliente_direccion,
    p_descripcion,
    p_valor_estimado,
    p_probabilidad_cierre,
    p_etapa,
    p_fecha_cierre_estimada,
    p_id_vendedor,
    p_nombre_vendedor,
    p_observaciones
  ) RETURNING id INTO v_id;

  -- Retornar resultado
  SELECT json_build_object(
    'success', true,
    'data', json_build_object(
      'id', v_id,
      'numero_oportunidad', v_numero_oportunidad
    )
  ) INTO v_result;

  RETURN v_result;
END;
$$;

-- Función para actualizar oportunidad de venta
CREATE OR REPLACE FUNCTION public.actualizar_oportunidad_venta(
  p_id integer,
  p_cliente_nombre varchar(255) DEFAULT NULL,
  p_cliente_telefono varchar(50) DEFAULT NULL,
  p_cliente_email varchar(255) DEFAULT NULL,
  p_cliente_dni_cuit varchar(50) DEFAULT NULL,
  p_cliente_empresa varchar(255) DEFAULT NULL,
  p_cliente_direccion text DEFAULT NULL,
  p_descripcion text DEFAULT NULL,
  p_valor_estimado numeric(10,2) DEFAULT NULL,
  p_probabilidad_cierre integer DEFAULT NULL,
  p_etapa varchar(50) DEFAULT NULL,
  p_fecha_cierre_estimada date DEFAULT NULL,
  p_id_op integer DEFAULT NULL,
  p_numero_op varchar(255) DEFAULT NULL,
  p_observaciones text DEFAULT NULL,
  p_activo boolean DEFAULT NULL
)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_result json;
BEGIN
  UPDATE public.oportunidades_venta
  SET
    cliente_nombre = COALESCE(p_cliente_nombre, cliente_nombre),
    cliente_telefono = COALESCE(p_cliente_telefono, cliente_telefono),
    cliente_email = COALESCE(p_cliente_email, cliente_email),
    cliente_dni_cuit = COALESCE(p_cliente_dni_cuit, cliente_dni_cuit),
    cliente_empresa = COALESCE(p_cliente_empresa, cliente_empresa),
    cliente_direccion = COALESCE(p_cliente_direccion, cliente_direccion),
    descripcion = COALESCE(p_descripcion, descripcion),
    valor_estimado = COALESCE(p_valor_estimado, valor_estimado),
    probabilidad_cierre = COALESCE(p_probabilidad_cierre, probabilidad_cierre),
    etapa = COALESCE(p_etapa, etapa),
    fecha_cierre_estimada = COALESCE(p_fecha_cierre_estimada, fecha_cierre_estimada),
    id_op = COALESCE(p_id_op, id_op),
    numero_op = COALESCE(p_numero_op, numero_op),
    observaciones = COALESCE(p_observaciones, observaciones),
    activo = COALESCE(p_activo, activo),
    updated_at = now()
  WHERE id = p_id;

  SELECT json_build_object('success', true) INTO v_result;
  RETURN v_result;
END;
$$;

