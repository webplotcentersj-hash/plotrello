DROP TRIGGER IF EXISTS trg_erp_retenciones_updated_at ON public.erp_retenciones;
CREATE TRIGGER trg_erp_retenciones_updated_at
BEFORE UPDATE ON public.erp_retenciones
FOR EACH ROW EXECUTE FUNCTION public.erp_set_updated_at();

