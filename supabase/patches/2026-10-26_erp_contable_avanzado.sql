-- =============================================================================
-- ERP contable avanzado
--   1) Retenciones y percepciones (efectuadas / sufridas)
--   2) Liquidación mensual de IVA (abierta / cerrada / presentada)
--   3) Cierre de períodos contables (bloquea asientos en períodos cerrados)
--   4) Cheques (cartera y propios) con historial + cobradores
--   5) Asientos modelo e índices de inflación (ajuste RT 6 simplificado)
--   6) Cuentas corrientes consolidadas (clientes relacionados)
--   7) Percepciones / no gravado / exento en facturas_compra (Libro IVA Digital)
--
-- Requiere el ERP base (plan_cuentas, asientos_contables, asientos_detalle,
-- facturas_venta, facturas_compra, cuentas_bancarias, clientes, proveedores, usuarios).
-- Es idempotente: se puede ejecutar más de una vez.
-- Ejecutar en Supabase → SQL Editor.
-- =============================================================================

BEGIN;

-- Función genérica updated_at (la reusa el resto del patch)
CREATE OR REPLACE FUNCTION public.erp_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

