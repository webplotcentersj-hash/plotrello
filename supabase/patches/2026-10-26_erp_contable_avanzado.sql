  fecha date NOT NULL DEFAULT CURRENT_DATE,
  tercero_tipo text NOT NULL DEFAULT 'Proveedor' CHECK (tercero_tipo IN ('Proveedor', 'Cliente', 'Otro')),
  id_proveedor integer REFERENCES public.proveedores(id) ON DELETE SET NULL,
  id_cliente integer REFERENCES public.clientes(id) ON DELETE SET NULL,
  tercero_nombre text NOT NULL,
  tercero_cuit text,
  base_imponible numeric(15,2) NOT NULL DEFAULT 0,
  alicuota numeric(7,4) NOT NULL DEFAULT 0,
  importe numeric(15,2) NOT NULL CHECK (importe >= 0),
  numero_certificado text,
  id_factura_compra integer REFERENCES public.facturas_compra(id) ON DELETE SET NULL,
  id_factura_venta integer REFERENCES public.facturas_venta(id) ON DELETE SET NULL,
  id_asiento_contable integer REFERENCES public.asientos_contables(id) ON DELETE SET NULL,
  estado text NOT NULL DEFAULT 'Vigente' CHECK (estado IN ('Vigente', 'Anulada')),
  observaciones text,
  id_usuario integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

