CREATE OR REPLACE FUNCTION public.erp_periodo_esta_cerrado(p_fecha date)
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.erp_periodos_contables p
    WHERE p.periodo = to_char(p_fecha, 'YYYY-MM')
      AND p.estado = 'Cerrado'
  );
$$;

-- Bloquea crear / modificar / borrar asientos con fecha en un período cerrado.
CREATE OR REPLACE FUNCTION public.erp_bloquear_asiento_periodo_cerrado()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF public.erp_periodo_esta_cerrado(OLD.fecha) THEN
      RAISE EXCEPTION 'El período % está cerrado: no se pueden modificar asientos.', to_char(OLD.fecha, 'YYYY-MM');
    END IF;
    RETURN OLD;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF public.erp_periodo_esta_cerrado(OLD.fecha) THEN
      RAISE EXCEPTION 'El período % está cerrado: no se pueden modificar asientos.', to_char(OLD.fecha, 'YYYY-MM');
    END IF;
  END IF;

  IF public.erp_periodo_esta_cerrado(NEW.fecha) THEN
    RAISE EXCEPTION 'El período % está cerrado: no se pueden crear asientos.', to_char(NEW.fecha, 'YYYY-MM');
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_erp_asientos_periodo_cerrado ON public.asientos_contables;
CREATE TRIGGER trg_erp_asientos_periodo_cerrado
BEFORE INSERT OR UPDATE OR DELETE ON public.asientos_contables
FOR EACH ROW EXECUTE FUNCTION public.erp_bloquear_asiento_periodo_cerrado();

-- Lo mismo para las líneas del asiento (según la fecha del asiento padre).
CREATE OR REPLACE FUNCTION public.erp_bloquear_detalle_periodo_cerrado()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_fecha date;
  v_id integer;
BEGIN
  v_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.id_asiento ELSE NEW.id_asiento END;
  SELECT a.fecha INTO v_fecha FROM public.asientos_contables a WHERE a.id = v_id;
  IF v_fecha IS NOT NULL AND public.erp_periodo_esta_cerrado(v_fecha) THEN
    RAISE EXCEPTION 'El período % está cerrado: no se pueden modificar líneas de asiento.', to_char(v_fecha, 'YYYY-MM');
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_erp_asientos_detalle_periodo_cerrado ON public.asientos_detalle;
CREATE TRIGGER trg_erp_asientos_detalle_periodo_cerrado
BEFORE INSERT OR UPDATE OR DELETE ON public.asientos_detalle
FOR EACH ROW EXECUTE FUNCTION public.erp_bloquear_detalle_periodo_cerrado();

