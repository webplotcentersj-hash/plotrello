-- =============================================================================
-- RLS + grants (misma política permisiva que el resto del ERP: la app usa anon;
-- los permisos finos se controlan en la UI).
-- =============================================================================
DO $$
DECLARE
  t text;
  s text;
  tablas text[] := ARRAY[
    'erp_retenciones',
    'erp_liquidaciones_iva',
    'erp_periodos_contables',
    'erp_cheques',
    'erp_cheques_historial',
    'erp_cobradores',
    'erp_cobrador_clientes',
    'erp_asientos_modelo',
    'erp_asientos_modelo_detalle',
    'erp_indices_inflacion',
    'erp_clientes_relacionados'
  ];
BEGIN
  FOREACH t IN ARRAY tablas LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO anon, authenticated', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || ' acceso', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true)',
      t || ' acceso', t
    );
    -- Solo las tablas con columna "id" tienen secuencia (periodos e índices usan el período como PK).
    IF EXISTS (
      SELECT 1 FROM information_schema.columns c
      WHERE c.table_schema = 'public' AND c.table_name = t AND c.column_name = 'id'
    ) THEN
      s := pg_get_serial_sequence('public.' || t, 'id');
      IF s IS NOT NULL THEN
        EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO anon, authenticated', s);
      END IF;
    END IF;
  END LOOP;
END $$;

GRANT EXECUTE ON FUNCTION public.erp_periodo_esta_cerrado(date) TO anon, authenticated;

COMMIT;
