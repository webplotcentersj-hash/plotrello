  naturaleza text NOT NULL DEFAULT 'Retención' CHECK (naturaleza IN ('Retención', 'Percepción')),
  sentido text NOT NULL CHECK (sentido IN ('Efectuada', 'Sufrida')),
  impuesto text NOT NULL CHECK (impuesto IN ('Ganancias', 'IVA', 'IIBB', 'SUSS', 'SIRCREB', 'SIRTAC', 'Municipal', 'Otro')),
  regimen text,
